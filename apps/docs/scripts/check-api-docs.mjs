// Fails when a package entry exports something without a doc comment: TypeDoc's `notDocumented`
// validation, with its warnings treated as errors, over every entry each package's `exports`
// points at (every subpath and condition), so a new entry is checked without editing this file.
// Run by `cargo xtask check ts` (`pnpm --filter @laminapdf/docs run check:api-docs`).

import { readFileSync } from "node:fs";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { Application, LogLevel } from "typedoc";

const ROOT = new URL("../../../", import.meta.url);
const fromRoot = (p) => fileURLToPath(new URL(p, ROOT));

/** The packages whose exports are checked. @laminapdf/wasm is left out: its code and types are
 * generated by wasm-bindgen, with no hand-written comments to check. */
const PACKAGES = ["sdk", "render", "render-pdfium", "render-hayro", "viewer"];

/** Every `.js` file a package's `exports` points at (each subpath and condition). */
function exportedFiles(exports) {
  if (typeof exports === "string") return exports.endsWith(".js") ? [exports] : [];
  if (exports === null || typeof exports !== "object") return [];
  return Object.values(exports).flatMap(exportedFiles);
}

/** A package's entry sources: each exported `dist/**.js`, as the `src/**.ts` it is built from. */
function entriesOf(dir) {
  const manifest = JSON.parse(readFileSync(fromRoot(`packages/${dir}/package.json`), "utf8"));
  const files = new Set(exportedFiles(manifest.exports));
  return {
    name: manifest.name,
    tsconfig: `packages/${dir}/tsconfig.build.json`,
    entries: [...files].map((f) => `packages/${dir}/${f.replace(/^\.\/dist\//, "src/").replace(/\.js$/, ".ts")}`),
  };
}

let failed = 0;
for (const pkg of PACKAGES.map(entriesOf)) {
  const app = await Application.bootstrap({
    entryPoints: pkg.entries.map(fromRoot),
    tsconfig: fromRoot(pkg.tsconfig),
    // Type errors are tsc's job (and the wasm-bindgen types need `cargo xtask wasm` first).
    readme: "none",
    skipErrorChecking: true,
    excludeInternal: true,
    excludePrivate: true,
    excludeProtected: true,
    excludeExternals: true,
    validation: { notExported: false, invalidLink: false, notDocumented: true },
    // The guideline's "exported symbols and public methods": declarations, not every property.
    requiredToBeDocumented: ["Enum", "Variable", "Function", "Class", "Interface", "TypeAlias", "Method", "Accessor"],
    treatValidationWarningsAsErrors: true,
    logLevel: LogLevel.Warn,
  });
  const project = await app.convert();
  if (project === undefined) {
    console.error(`${pkg.name}: TypeDoc could not convert the entries`);
    failed++;
    continue;
  }
  app.validate(project);
  const warnings = app.logger.warningCount + app.logger.errorCount;
  if (warnings > 0) {
    console.error(`${pkg.name}: ${warnings} undocumented export(s), listed above`);
    failed++;
  } else console.log(`${pkg.name}: every export is documented`);
}
process.exitCode = failed > 0 ? 1 : 0;
