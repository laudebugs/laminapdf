//! Tauri's build step. App commands go through an app manifest, so each needs an explicit
//! `allow-*` permission in a capability file before the webview may call it (ADR 0008 §6).

use std::process::ExitCode;

/// Every command a release build has.
const COMMANDS: &[&str] = &[
    "app_info",
    "open_dialog",
    "page_info",
    "close_document",
    "unlock_document",
    "cancel_tiles",
    "take_pending_opens",
    "recent_list",
    "recent_open",
    "recent_remove",
    "recent_clear",
    "preferences",
    "set_preferences",
    "new_window",
    "move_tab",
    "window_list",
    "set_window_title",
    "take_pending_tabs",
    "menu_state",
    "close_window",
    "quit",
    "save_copy",
    "tab_drag_start",
    "tab_drag_end",
];

/// With the `e2e` feature: the end-to-end tests' commands too.
const E2E_COMMANDS: &[&str] = &[
    "app_info",
    "open_dialog",
    "page_info",
    "close_document",
    "unlock_document",
    "cancel_tiles",
    "take_pending_opens",
    "recent_list",
    "recent_open",
    "recent_remove",
    "recent_clear",
    "preferences",
    "set_preferences",
    "new_window",
    "move_tab",
    "window_list",
    "set_window_title",
    "take_pending_tabs",
    "menu_state",
    "close_window",
    "quit",
    "save_copy",
    "tab_drag_start",
    "tab_drag_end",
    "debug_kill_engine",
    "e2e_queue_pick",
    "e2e_interactive",
    "e2e_focus",
    "e2e_menu_click",
    "e2e_menu_snapshot",
];

fn main() -> ExitCode {
    let commands = if std::env::var_os("CARGO_FEATURE_E2E").is_some() {
        E2E_COMMANDS
    } else {
        // tauri-build writes a permission file per command but never deletes one, so a file
        // left by an earlier e2e build would put the e2e commands' names in this build.
        for command in E2E_COMMANDS.iter().filter(|command| !COMMANDS.contains(command)) {
            let stale = std::path::PathBuf::from(format!("permissions/autogenerated/{command}.toml"));
            if stale.exists()
                && let Err(error) = std::fs::remove_file(&stale)
            {
                println!("cargo:warning=could not remove {}: {error}", stale.display());
                return ExitCode::FAILURE;
            }
        }
        COMMANDS
    };
    let manifest = tauri_build::AppManifest::new().commands(commands);
    match tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            // A build script's stderr shows when it fails; `cargo:warning` keeps the reason visible.
            println!("cargo:warning=tauri-build failed: {error:#}");
            ExitCode::FAILURE
        }
    }
}
