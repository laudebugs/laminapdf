//! Generate, then edit: build a document, save it, open the bytes, change the Info
//! dictionary with an op (undoable and serialisable), and save incrementally: the original
//! bytes stay as they are, with one revision appended.
//!
//! ```sh
//! cargo run -p laminapdf --example generate_then_edit -- [out-dir]   # writes <out-dir>/generate_then_edit.pdf
//! ```

use std::error::Error;
use std::path::PathBuf;

use laminapdf::{
    BuildOptions, Builder, Document, InfoPatch, Metadata, Op, OpenOptions, PageSize, PointPt, Pt, SaveMode,
    SaveOptions, SetInfo, Standard14,
};

fn main() -> Result<(), Box<dyn Error>> {
    let out = PathBuf::from(std::env::args().nth(1).unwrap_or_else(|| "target/examples-out".into()));
    std::fs::create_dir_all(&out)?;
    std::fs::write(out.join("generate_then_edit.pdf"), build()?)?;
    Ok(())
}

/// The document's bytes: the generated file followed by the edit's revision.
pub(crate) fn build() -> Result<Vec<u8>, Box<dyn Error>> {
    // 1. Generate and save (a new document is always a full rewrite).
    let options = BuildOptions::default()
        .with_id(*b"lamina-ex-edit!!")
        .with_producer("lamina examples")
        .with_creation_date("D:20261030120000Z".parse()?);
    let mut b = Builder::new(options);
    let helvetica = b.standard_font(Standard14::Helvetica)?;
    let mut page = b.page(PageSize::A4);
    page.surface().text(
        "Draft report",
        &helvetica,
        Pt::new(20.0),
        PointPt::from_points(72.0, 96.0),
    )?;
    page.finish()?;
    b.metadata(Metadata::default().with_title("Draft report"));
    let generated = b.finish()?.save(&SaveOptions::new())?.bytes;

    // 2. Open the bytes and edit them with an op: one transaction, which `undo` could revert.
    let mut doc = Document::open_bytes(generated.clone(), OpenOptions::default())?;
    let patch = InfoPatch::new()
        .title(Some("Final report"))
        .author(Some("Ada Lovelace"));
    doc.apply(vec![Op::from(SetInfo::new(patch, Some("D:20261030130000Z".parse()?)))])?;

    // 3. Save incrementally: the generated bytes, unchanged, then the appended revision.
    let options = SaveOptions::new().with_mode(SaveMode::Incremental);
    let edited = doc.save(&options)?.bytes;
    if !edited.starts_with(&generated) || doc.info()?.title.as_deref() != Some("Final report") {
        return Err("the incremental save did not append to the generated file".into());
    }
    Ok(edited)
}
