//! `cargo xtask version`: one version for the whole library (ADR 0017).
//!
//! Changesets versions the npm packages (one `fixed` group in `.changeset/config.json`:
//! `@laminapdf/wasm`, `@laminapdf/sdk` and the render packages); Changesets doesn't know Cargo or
//! TypeScript constants, so `version sync` copies that version into the rest:
//!
//! - `[workspace.package] version` in the root `Cargo.toml` (every member inherits it with
//!   `version.workspace = true`, which `--check` requires);
//! - the `version` of every internal `[workspace.dependencies]` entry (`path = "crates/…"`), which
//!   `cargo publish` will need;
//! - the internal crates' entries in every tracked `Cargo.lock` (the root's, `fuzz/`'s and the
//!   spikes' that depend on the core crates by path; edited in place, so the sync needs neither the
//!   network nor a build, and `--locked` builds keep working);
//! - the root `CHANGELOG.md`, merged from every member's `CHANGELOG.md` (Changesets writes one per
//!   package, and a changeset that names only some members leaves the others with an empty
//!   heading): per version, newest first, the union of their entries in the order Major, Minor,
//!   Patch, without duplicates or Changesets' dependency-bump entries (every internal dependency
//!   is at the one version);
//! - the `VERSION = "…"` literal in `packages/sdk/src/version.ts`, which the worker handshake
//!   compares (L2a). It stays a constant rather than a JSON import of `package.json`, which would
//!   change how each of `@laminapdf/sdk`'s export conditions bundles; the sync and
//!   `test/version.test.ts` keep the two in step.
//!
//! `--check` fails, listing each stale file, when the sync would change anything, or when a member
//! crate sets its own version. It reads files only, so it runs in `cargo xtask check docs`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde_json::Value;

/// The package whose `VERSION` constant is synced; it comes first in the group.
const LEAD_PACKAGE: &str = "@laminapdf/sdk";
/// The packages the fixed group must contain: `@laminapdf/sdk` is only correct with the
/// `@laminapdf/wasm` built from the same commit (ADR 0017).
const REQUIRED_MEMBERS: [&str; 2] = ["@laminapdf/wasm", LEAD_PACKAGE];
/// Where the workspace's npm packages live (`packages/<dir>/package.json`).
const PACKAGES_DIR: &str = "packages";
/// `@laminapdf/sdk`'s `VERSION` constant, and the declaration (after any indentation) that sets it.
const VERSION_TS: &str = "packages/sdk/src/version.ts";
const VERSION_TS_DECL: &str = "export const VERSION = \"";
/// The changelog sections Changesets writes, in the root changelog's order; others follow them.
const CHANGELOG_SECTIONS: [&str; 3] = ["Major Changes", "Minor Changes", "Patch Changes"];
/// What Changesets writes under a release without entries; the root changelog writes it too.
const NO_CHANGES: &str = "No changes in this release.";
/// The entry Changesets adds for bumped internal dependencies, left out of the root changelog.
const DEPENDENCY_ENTRY: &str = "- Updated dependencies";
/// The lockfiles to sync outside a git checkout (tests): every tracked `Cargo.lock` otherwise
/// ([`lockfiles`]); one without internal path packages is left as it is.
const LOCKFILES: [&str; 2] = ["Cargo.lock", "fuzz/Cargo.lock"];
/// The root changelog's preamble; the package changelog's entries follow it.
const CHANGELOG_HEADER: &str = "# Changelog\n\n\
<!-- Generated by `cargo xtask version sync` from the fixed group's packages/*/CHANGELOG.md, which Changesets \
writes (`pnpm changeset version`); edit the changesets, not this file. -->\n\n\
Lamina PDF is versioned in lockstep (ADR 0017): every crate and every npm package (`@laminapdf/wasm`, \
`@laminapdf/sdk`, `@laminapdf/render`, `@laminapdf/render-hayro`, `@laminapdf/render-pdfium`, \
`@laminapdf/viewer`) share one version, so these entries cover all of them. Versions from 0.2.0-alpha.2 on are \
published to crates.io and npm; earlier ones were only tagged (0.2.0-alpha.1's release run failed its checks, \
so nothing was published from it).\n";

/// What `cargo xtask version …` was asked to do.
#[derive(Debug, PartialEq, Eq)]
pub(crate) enum Command {
    /// `sync [--check]`.
    Sync { check: bool },
    /// `check-tag <tag>`: the release lane's check that a tag names the current version.
    CheckTag(String),
}

const USAGE: &str = "usage: cargo xtask version sync [--check] | cargo xtask version check-tag <tag>";

pub(crate) fn parse_args(args: &[String]) -> Result<Command> {
    match args {
        [cmd] if cmd == "sync" => Ok(Command::Sync { check: false }),
        [cmd, flag] if cmd == "sync" && flag == "--check" => Ok(Command::Sync { check: true }),
        [cmd, tag] if cmd == "check-tag" => Ok(Command::CheckTag(tag.clone())),
        _ => bail!(USAGE),
    }
}

pub(crate) fn run(root: &Path, command: &Command) -> Result<()> {
    match command {
        Command::Sync { check } => sync(root, *check),
        Command::CheckTag(tag) => check_tag(root, tag),
    }
}

/// `version sync [--check]`.
fn sync(root: &Path, check: bool) -> Result<()> {
    crate::step(if check {
        "version sync --check: crates, lockfiles, CHANGELOG.md and version.ts at the npm fixed group's version"
    } else {
        "version sync: the npm fixed group's version into the crates, lockfiles, CHANGELOG.md and version.ts"
    });
    let plan = plan(root)?;
    if check {
        let mut problems = plan.problems;
        problems.extend(
            plan.updates
                .iter()
                .map(|(path, _)| format!("{} is out of sync: run `cargo xtask version sync`", display(root, path))),
        );
        if !problems.is_empty() {
            bail!(
                "versions are out of sync with the npm fixed group ({}, ADR 0017):\n  {}",
                plan.version,
                problems.join("\n  ")
            );
        }
        println!(
            "every crate, lockfile entry, CHANGELOG.md and {VERSION_TS} is at {}",
            plan.version
        );
        return Ok(());
    }
    if !plan.problems.is_empty() {
        bail!("can't sync the versions (ADR 0017):\n  {}", plan.problems.join("\n  "));
    }
    for (path, text) in &plan.updates {
        fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
        println!("updated {}", display(root, path));
    }
    if plan.updates.is_empty() {
        println!("already at {}", plan.version);
    }
    Ok(())
}

/// `version check-tag <tag>`: the tag must be `v<version>`.
fn check_tag(root: &Path, tag: &str) -> Result<()> {
    let version = fixed_group_version(root)?.version;
    let expected = format!("v{version}");
    if tag != expected {
        bail!("tag {tag:?} doesn't name the current version: expected {expected:?} (ADR 0017)");
    }
    println!("tag {tag} names version {version}");
    Ok(())
}

fn display(root: &Path, path: &Path) -> String {
    crate::util::slash_path(path.strip_prefix(root).unwrap_or(path))
}

/// What a sync would do: the files to rewrite (with their new text) and the problems it can't fix.
struct Plan {
    version: String,
    updates: Vec<(PathBuf, String)>,
    problems: Vec<String>,
}

fn plan(root: &Path) -> Result<Plan> {
    let FixedGroup {
        version,
        members: packages,
    } = fixed_group_version(root)?;
    let mut updates = Vec::new();
    let mut problems = crate::changesets::private_packages_outside_ignore(root)?;
    let mut update = |path: PathBuf, old: &str, new: String| {
        if old != new {
            updates.push((path, new));
        }
    };

    let manifest_path = root.join("Cargo.toml");
    let manifest = read(&manifest_path)?;
    let synced = sync_manifest(&manifest, &version)?;
    // The line edits are checked by parsing their result: a manifest laid out in a way they don't
    // handle fails here instead of being half-synced.
    problems.extend(manifest_problems(&synced, &version)?);
    update(manifest_path, &manifest, synced);

    let members = member_manifests(root, &manifest)?;
    let mut internal = BTreeSet::new();
    for path in &members {
        let text = read(path)?;
        let (name, inherits) = member_version(&text).with_context(|| format!("reading {}", path.display()))?;
        if !inherits {
            problems.push(format!(
                "{}: set `version.workspace = true` (every crate shares the workspace version)",
                display(root, path)
            ));
        }
        internal.insert(name);
    }

    for path in lockfiles(root) {
        let text = read(&path)?;
        let synced = sync_lockfile(&text, &internal, &version);
        update(path, &text, synced);
    }

    let changelog_path = root.join("CHANGELOG.md");
    let mut sources = Vec::with_capacity(packages.len());
    for (name, dir) in &packages {
        let path = dir.join("CHANGELOG.md");
        // A member gets its changelog at its first `pnpm changeset version`; @laminapdf/sdk has one.
        if name == LEAD_PACKAGE || path.is_file() {
            sources.push((name.as_str(), read(&path)?));
        }
    }
    let sources: Vec<(&str, &str)> = sources.iter().map(|(name, text)| (*name, text.as_str())).collect();
    let current = fs::read_to_string(&changelog_path).unwrap_or_default();
    update(changelog_path, &current, root_changelog(&sources)?);

    let version_ts_path = root.join(VERSION_TS);
    let version_ts = read(&version_ts_path)?;
    update(version_ts_path, &version_ts, sync_version_ts(&version_ts, &version)?);

    Ok(Plan {
        version,
        updates,
        problems,
    })
}

/// Every tracked `Cargo.lock` (`git ls-files`), else the [`LOCKFILES`] that exist.
fn lockfiles(root: &Path) -> Vec<PathBuf> {
    let tracked = std::process::Command::new("git")
        .args(["ls-files", "-z", "--", "*Cargo.lock"])
        .current_dir(root)
        .output()
        .ok()
        .filter(|o| o.status.success() && !o.stdout.is_empty());
    match tracked {
        Some(output) => output
            .stdout
            .split(|b| *b == 0)
            .filter(|p| !p.is_empty())
            .map(|p| root.join(String::from_utf8_lossy(p).as_ref()))
            .filter(|p| p.is_file())
            .collect(),
        None => LOCKFILES.iter().map(|l| root.join(l)).filter(|p| p.is_file()).collect(),
    }
}

fn read(path: &Path) -> Result<String> {
    fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))
}

/// The npm packages released together, as `.changeset/config.json` and their manifests say.
pub(crate) struct FixedGroup {
    /// Their one version.
    pub(crate) version: String,
    /// Each member's name and folder: [`LEAD_PACKAGE`] first, then in the config's order.
    pub(crate) members: Vec<(String, PathBuf)>,
}

/// The fixed group and its version: every member's `package.json` must have it.
pub(crate) fn fixed_group_version(root: &Path) -> Result<FixedGroup> {
    let names = fixed_group(&read(&root.join(".changeset/config.json"))?)?;
    let mut found = find_packages(root, &names)?;
    let mut members = Vec::with_capacity(names.len());
    let mut versions = Vec::with_capacity(names.len());
    for name in names {
        let Some((dir, package)) = found.remove(&name) else {
            bail!(".changeset/config.json's fixed group names {name}, which no {PACKAGES_DIR}/*/package.json is");
        };
        let version = package
            .get("version")
            .and_then(Value::as_str)
            .with_context(|| format!("{} has no version", display(root, &dir.join("package.json"))))?
            .to_owned();
        versions.push((name.clone(), version));
        members.push((name, dir));
    }
    let Some((lead, first)) = versions.first() else {
        bail!("no packages in the fixed group");
    };
    if let Some((name, other)) = versions.iter().find(|(_, v)| v != first) {
        bail!(
            "the fixed group disagrees: {name} is at {other}, not {first} like {lead} \
             (run `pnpm changeset version`, or set it by hand for a new member)"
        );
    }
    if !is_version(first) {
        bail!("{first:?} is not a semantic version (MAJOR.MINOR.PATCH[-PRE])");
    }
    Ok(FixedGroup {
        version: first.clone(),
        members,
    })
}

/// The members of the one `fixed` group in `.changeset/config.json` (ADR 0017: one version),
/// [`LEAD_PACKAGE`] first; it must contain the [`REQUIRED_MEMBERS`].
fn fixed_group(config: &str) -> Result<Vec<String>> {
    const NOT_NAMES: &str = ".changeset/config.json: the `fixed` group must be an array of package names";
    let config: Value = serde_json::from_str(config).context(".changeset/config.json is not valid JSON")?;
    let groups = config
        .get("fixed")
        .and_then(Value::as_array)
        .context(".changeset/config.json has no `fixed` array (ADR 0017)")?;
    let [group] = groups.as_slice() else {
        bail!(
            ".changeset/config.json must have exactly one `fixed` group, not {} (ADR 0017: one version)",
            groups.len()
        );
    };
    let names = group
        .as_array()
        .context(NOT_NAMES)?
        .iter()
        .map(|name| name.as_str().map(str::to_owned).context(NOT_NAMES))
        .collect::<Result<Vec<_>>>()?;
    if let Some(missing) = REQUIRED_MEMBERS.iter().find(|r| !names.iter().any(|n| n == *r)) {
        bail!(
            ".changeset/config.json's `fixed` group must include {missing} (ADR 0017: {} ship together)",
            REQUIRED_MEMBERS.join(" and ")
        );
    }
    let mut ordered = vec![LEAD_PACKAGE.to_owned()];
    ordered.extend(names.into_iter().filter(|n| n != LEAD_PACKAGE));
    Ok(ordered)
}

/// The folder and parsed `package.json` of each package in `names`, from `packages/*/`. A
/// manifest that doesn't parse or has no name is skipped with a warning, unless its folder is the
/// one a member's name points to (`@laminapdf/render` → `packages/render`); two folders with the same
/// member name fail.
fn find_packages(root: &Path, names: &[String]) -> Result<BTreeMap<String, (PathBuf, Value)>> {
    let folders = package_folders(root, PACKAGES_DIR)?;
    let mut found: BTreeMap<String, (PathBuf, Value)> = BTreeMap::new();
    for folder in folders {
        let path = folder.join("package.json");
        let parsed = read_json(&path).and_then(|package| {
            let name = package
                .get("name")
                .and_then(Value::as_str)
                .context("no `name`")?
                .to_owned();
            Ok((name, package))
        });
        let (name, package) = match parsed {
            Ok(parsed) => parsed,
            Err(error) => {
                let folder_name = folder.file_name().and_then(|f| f.to_str()).unwrap_or_default();
                let expected = names.iter().find(|n| n.rsplit('/').next() == Some(folder_name));
                if let Some(member) = expected {
                    return Err(error.context(format!(
                        "{} (the folder of fixed group member {member})",
                        display(root, &path)
                    )));
                }
                eprintln!("warning: skipping {}: {error:#}", display(root, &path));
                continue;
            }
        };
        if !names.contains(&name) {
            continue;
        }
        if let Some((other, _)) = found.get(&name) {
            bail!(
                "{name} is the name of both {} and {}",
                display(root, other),
                display(root, &folder)
            );
        }
        found.insert(name, (folder, package));
    }
    Ok(found)
}

/// The folders under `root/dir` that hold a `package.json`, sorted.
pub(crate) fn package_folders(root: &Path, dir: &str) -> Result<Vec<PathBuf>> {
    let dir = root.join(dir);
    let mut folders: Vec<PathBuf> = fs::read_dir(&dir)
        .with_context(|| format!("listing {}", dir.display()))?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.join("package.json").is_file())
        .collect();
    folders.sort();
    Ok(folders)
}

pub(crate) fn read_json(path: &Path) -> Result<Value> {
    serde_json::from_str(&read(path)?).with_context(|| format!("{} is not JSON", path.display()))
}

/// `version.ts` with the string literal of its `export const VERSION = "…"` declaration set to
/// `version`; the indentation, the rest of the line (`as const;`, a comment) and its line ending
/// are kept.
fn sync_version_ts(text: &str, version: &str) -> Result<String> {
    let mut found = false;
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let (indent, rest) = line.split_at(line.len() - line.trim_start().len());
        let Some(literal) = rest.strip_prefix(VERSION_TS_DECL) else {
            out.push_str(line);
            continue;
        };
        if found {
            bail!("{VERSION_TS} sets VERSION twice");
        }
        found = true;
        let close = literal
            .find('"')
            .with_context(|| format!("{VERSION_TS}: VERSION's string literal is not closed on its line"))?;
        let (_, tail) = literal.split_at(close);
        let _ = write!(out, "{indent}{VERSION_TS_DECL}{version}{tail}");
    }
    if !found {
        bail!("{VERSION_TS} has no `{VERSION_TS_DECL}…\"` declaration");
    }
    Ok(out)
}

/// `MAJOR.MINOR.PATCH` with an optional `-pre.release` (letters, digits, `-`, dots); no build
/// metadata. Enough to keep a stray quote or space out of the manifests.
pub(crate) fn is_version(text: &str) -> bool {
    let (core, pre) = text.split_once('-').map_or((text, None), |(c, p)| (c, Some(p)));
    let numbers: Vec<&str> = core.split('.').collect();
    numbers.len() == 3
        && numbers
            .iter()
            .all(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
        && pre.is_none_or(|pre| {
            pre.split('.')
                .all(|id| !id.is_empty() && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-'))
        })
}

/// The root manifest with `[workspace.package] version` and each internal workspace dependency's
/// `version` set to `version`. Line based, so comments and layout survive.
fn sync_manifest(manifest: &str, version: &str) -> Result<String> {
    let mut section = "";
    let mut set_package_version = false;
    let mut out = String::with_capacity(manifest.len() + 512);
    for line in manifest.split_inclusive('\n') {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            section = trimmed;
        }
        let key = trimmed.split('=').next().unwrap_or_default().trim();
        if section == "[workspace.package]" && key == "version" && line.contains("version = \"") {
            out.push_str(&with_version(line, version));
            set_package_version = true;
        } else if section == "[workspace.dependencies]" && is_internal_dependency(trimmed) {
            out.push_str(&with_version(line, version));
        } else {
            out.push_str(line);
        }
    }
    if !set_package_version {
        bail!("Cargo.toml has no `version = \"…\"` line in [workspace.package]");
    }
    Ok(out)
}

/// `name = { path = "crates/…", … }` on one line.
fn is_internal_dependency(line: &str) -> bool {
    !line.starts_with('#')
        && line
            .split_once('=')
            .is_some_and(|(_, value)| value.trim_start().starts_with('{') && value.contains("path = \"crates/"))
}

/// `line` (an inline-table dependency) with its `version = "…"` set, or added after `{ `.
fn with_version(line: &str, version: &str) -> String {
    const KEY: &str = "version = \"";
    if let Some(start) = line.find(KEY) {
        let value_start = start + KEY.len();
        if let Some(len) = line.get(value_start..).and_then(|rest| rest.find('"')) {
            let (head, tail) = line.split_at(value_start);
            return format!("{head}{version}{}", tail.get(len..).unwrap_or_default());
        }
    }
    line.replacen("{ ", &format!("{{ version = \"{version}\", "), 1)
}

/// What a synced root manifest must say: the workspace version, and that version on every
/// internal workspace dependency.
fn manifest_problems(manifest: &str, version: &str) -> Result<Vec<String>> {
    let table: toml::Table = toml::from_str(manifest).context("Cargo.toml is not valid TOML")?;
    let workspace = table.get("workspace").context("Cargo.toml has no [workspace]")?;
    let mut problems = Vec::new();
    let package_version = workspace
        .get("package")
        .and_then(|p| p.get("version"))
        .and_then(toml::Value::as_str);
    if package_version != Some(version) {
        problems.push(format!(
            "Cargo.toml: [workspace.package] version is {package_version:?}, not {version:?}"
        ));
    }
    for (name, dep) in workspace
        .get("dependencies")
        .and_then(toml::Value::as_table)
        .into_iter()
        .flatten()
    {
        let internal = dep
            .get("path")
            .and_then(toml::Value::as_str)
            .is_some_and(|p| p.starts_with("crates/"));
        let dep_version = dep.get("version").and_then(toml::Value::as_str);
        if internal && dep_version != Some(version) {
            problems.push(format!(
                "Cargo.toml: [workspace.dependencies] {name} has version {dep_version:?}, not {version:?} \
                 (write it as one inline table: `{name} = {{ path = \"crates/…\", … }}`)"
            ));
        }
    }
    Ok(problems)
}

/// The manifests of the root workspace's members (`[workspace] members`, with `dir/*` and
/// `dir/*/sub` globs expanded: `apps/*/src-tauri` is the Tauri apps' crates).
fn member_manifests(root: &Path, manifest: &str) -> Result<Vec<PathBuf>> {
    let table: toml::Table = toml::from_str(manifest).context("Cargo.toml is not valid TOML")?;
    let members = table
        .get("workspace")
        .and_then(|w| w.get("members"))
        .and_then(toml::Value::as_array)
        .context("Cargo.toml has no [workspace] members")?;
    let mut manifests = Vec::new();
    for member in members {
        let member = member.as_str().context("[workspace] members must be strings")?;
        if let Some((dir, sub)) = split_glob(member)? {
            let mut found: Vec<PathBuf> = fs::read_dir(root.join(dir))
                .with_context(|| format!("listing {dir}"))?
                .filter_map(|entry| entry.ok().map(|e| e.path().join(sub).join("Cargo.toml")))
                .filter(|path| path.is_file())
                .collect();
            found.sort();
            manifests.extend(found);
        } else {
            manifests.push(root.join(member).join("Cargo.toml"));
        }
    }
    Ok(manifests)
}

/// A member glob as the folder before its `*` and the path after it (`""` for `dir/*`), or `None`
/// for a plain path. Only one `*`, as a whole path segment, is supported.
fn split_glob(member: &str) -> Result<Option<(&str, &str)>> {
    if !member.contains('*') {
        return Ok(None);
    }
    if let Some(dir) = member.strip_suffix("/*")
        && !dir.contains('*')
    {
        return Ok(Some((dir, "")));
    }
    match member.split_once("/*/") {
        Some((dir, sub)) if !dir.contains('*') && !sub.contains('*') => Ok(Some((dir, sub))),
        _ => bail!("member glob {member:?}: only `dir/*` and `dir/*/sub` are supported"),
    }
}

/// A member manifest's package name, and whether it inherits the workspace version.
fn member_version(manifest: &str) -> Result<(String, bool)> {
    let table: toml::Table = toml::from_str(manifest).context("not valid TOML")?;
    let package = table.get("package").context("no [package]")?;
    let name = package
        .get("name")
        .and_then(toml::Value::as_str)
        .context("no package name")?
        .to_owned();
    let inherits = package
        .get("version")
        .and_then(|v| v.get("workspace"))
        .and_then(toml::Value::as_bool)
        == Some(true);
    Ok((name, inherits))
}

/// `lockfile` with the `version` of each `[[package]]` named in `internal` and without a `source`
/// (a path package, not a registry crate of the same name) set to `version`.
fn sync_lockfile(lockfile: &str, internal: &BTreeSet<String>, version: &str) -> String {
    let mut out = String::with_capacity(lockfile.len());
    // Lockfile entries are blank-line separated blocks; `name`, `version` and `source` come first.
    for block in lockfile.split_inclusive("\n\n") {
        let name = block
            .lines()
            .find_map(|l| l.strip_prefix("name = \"").and_then(|r| r.strip_suffix('"')));
        let is_path_package = block.starts_with("[[package]]") && !block.lines().any(|l| l.starts_with("source = "));
        if is_path_package && name.is_some_and(|n| internal.contains(n)) {
            for line in block.split_inclusive('\n') {
                if line.starts_with("version = \"") {
                    let _ = writeln!(out, "version = \"{version}\"");
                } else {
                    out.push_str(line);
                }
            }
        } else {
            out.push_str(block);
        }
    }
    out
}

/// One release in a changelog: its sections (`### Minor Changes`, or `""` for entries before any
/// section heading), each with its entries (`- …` and the lines that continue it).
type Release = Vec<(String, Vec<String>)>;

/// The root `CHANGELOG.md`: [`CHANGELOG_HEADER`], then every release of the members' changelogs
/// (`(name, text)`, each starting with `# <name>`), newest first; per release, the sections in
/// [`CHANGELOG_SECTIONS`] order and the union of the members' entries, in member order, without
/// duplicates or dependency bumps ([`is_dependency_entry`]).
fn root_changelog(changelogs: &[(&str, &str)]) -> Result<String> {
    let mut releases: Vec<(String, Release)> = Vec::new();
    for (name, text) in changelogs {
        for (version, sections) in parse_changelog(name, text)? {
            let Some(merged) = entry_for(&mut releases, &version) else {
                continue;
            };
            for (section, entries) in sections {
                let Some(kept) = entry_for(merged, &section) else {
                    continue;
                };
                for entry in entries {
                    if !is_dependency_entry(&entry, changelogs) && !kept.contains(&entry) {
                        kept.push(entry);
                    }
                }
            }
        }
    }
    releases.sort_by(|(a, _), (b, _)| compare_versions(b, a));
    let mut out = CHANGELOG_HEADER.to_owned();
    for (version, mut sections) in releases {
        let _ = writeln!(out, "\n## {version}");
        sections.retain(|(_, entries)| !entries.is_empty());
        let rank = |section: &str| {
            CHANGELOG_SECTIONS
                .iter()
                .position(|s| *s == section)
                .unwrap_or(CHANGELOG_SECTIONS.len())
        };
        // Stable: unknown sections keep the order they were first seen in.
        sections.sort_by_key(|(section, _)| if section.is_empty() { 0 } else { rank(section) + 1 });
        // One changeset can bump one member minor and another patch: list it once, under the
        // highest bump (the sections are in that order now).
        let mut listed: Vec<String> = Vec::new();
        for (_, entries) in &mut sections {
            entries.retain(|entry| !listed.contains(entry));
            listed.extend(entries.iter().cloned());
        }
        sections.retain(|(_, entries)| !entries.is_empty());
        if sections.is_empty() {
            let _ = writeln!(out, "\n{NO_CHANGES}");
        }
        for (section, entries) in sections {
            if !section.is_empty() {
                let _ = writeln!(out, "\n### {section}");
            }
            out.push('\n');
            for entry in entries {
                let _ = writeln!(out, "{entry}");
            }
        }
    }
    Ok(out)
}

/// Whether `entry` only says that internal dependencies were bumped: Changesets'
/// [`DEPENDENCY_ENTRY`] list, or a bare `- <member>@<version>` line.
fn is_dependency_entry(entry: &str, changelogs: &[(&str, &str)]) -> bool {
    entry.starts_with(DEPENDENCY_ENTRY)
        || entry
            .strip_prefix("- ")
            .and_then(|e| e.rsplit_once('@'))
            .is_some_and(|(name, version)| is_version(version) && changelogs.iter().any(|(n, _)| *n == name))
}

/// The value for `key` in an ordered list of pairs, added (empty) at the end if missing.
fn entry_for<'a, T: Default>(list: &'a mut Vec<(String, T)>, key: &str) -> Option<&'a mut T> {
    if !list.iter().any(|(k, _)| k == key) {
        list.push((key.to_owned(), T::default()));
    }
    list.iter_mut().find(|(k, _)| k == key).map(|(_, value)| value)
}

/// A package's `CHANGELOG.md` as Changesets writes it: `# <name>`, then `## <version>` releases
/// with `### <section>` headings and `- ` entries.
fn parse_changelog(name: &str, text: &str) -> Result<Vec<(String, Release)>> {
    let body = text
        .strip_prefix(&format!("# {name}\n"))
        .with_context(|| format!("{name}'s CHANGELOG.md must start with `# {name}` (Changesets writes it)"))?;
    let mut releases: Vec<(String, Release)> = Vec::new();
    for line in body.lines() {
        if let Some(version) = line.strip_prefix("## ") {
            let version = version.trim();
            if !is_version(version) {
                bail!("{name}'s CHANGELOG.md: {version:?} is not a version");
            }
            releases.push((version.to_owned(), Vec::new()));
            continue;
        }
        let Some((_, sections)) = releases.last_mut() else {
            if line.trim().is_empty() {
                continue;
            }
            bail!("{name}'s CHANGELOG.md: text before the first `## <version>`: {line:?}");
        };
        if let Some(section) = line.strip_prefix("### ") {
            sections.push((section.trim().to_owned(), Vec::new()));
        } else if line.trim() == NO_CHANGES {
            // Changesets' text for a release with no entries; the root changelog writes its own.
        } else if line.starts_with("- ") || !(line.is_empty() || line.starts_with(char::is_whitespace)) {
            // An entry, or a paragraph of its own (kept as one).
            if sections.is_empty() {
                sections.push((String::new(), Vec::new()));
            }
            if let Some((_, entries)) = sections.last_mut() {
                entries.push(line.to_owned());
            }
        } else if let Some(entry) = sections.last_mut().and_then(|(_, entries)| entries.last_mut()) {
            entry.push('\n');
            entry.push_str(line);
        }
    }
    for (_, sections) in &mut releases {
        for (_, entries) in sections {
            for entry in entries {
                entry.truncate(entry.trim_end().len());
            }
        }
    }
    Ok(releases)
}

/// `SemVer` precedence of two [`is_version`] strings (build metadata isn't allowed).
pub(crate) fn compare_versions(a: &str, b: &str) -> std::cmp::Ordering {
    use std::cmp::Ordering;
    fn split(version: &str) -> (Vec<u64>, Option<&str>) {
        let (core, pre) = version.split_once('-').map_or((version, None), |(c, p)| (c, Some(p)));
        (core.split('.').map(|n| n.parse().unwrap_or(u64::MAX)).collect(), pre)
    }
    let ((a_core, a_pre), (b_core, b_pre)) = (split(a), split(b));
    a_core.cmp(&b_core).then_with(|| match (a_pre, b_pre) {
        (None, None) => Ordering::Equal,
        (None, Some(_)) => Ordering::Greater,
        (Some(_), None) => Ordering::Less,
        (Some(a_pre), Some(b_pre)) => {
            let (mut a_ids, mut b_ids) = (a_pre.split('.'), b_pre.split('.'));
            loop {
                let order = match (a_ids.next(), b_ids.next()) {
                    (None, None) => return Ordering::Equal,
                    (None, Some(_)) => return Ordering::Less,
                    (Some(_), None) => return Ordering::Greater,
                    (Some(x), Some(y)) => match (x.parse::<u64>(), y.parse::<u64>()) {
                        (Ok(x), Ok(y)) => x.cmp(&y),
                        (Ok(_), Err(_)) => Ordering::Less,
                        (Err(_), Ok(_)) => Ordering::Greater,
                        (Err(_), Err(_)) => x.cmp(y),
                    },
                };
                if order != Ordering::Equal {
                    return order;
                }
            }
        }
    })
}

