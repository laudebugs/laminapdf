    /// A minimal todo file; `deps` is the raw Depends on value.
    pub(crate) fn todo(state: State, id: &str, deps: &str) -> TodoFile {
        TodoFile {
            state,
            file: format!("{id}-x.md"),
            text: format!(
                "# {id} — Title of {id}\n\n| Field | Value |\n| --- | --- |\n| ID | `{id}` |\n| Status | `{}` |\n\
                 | Depends on | {deps} |\n| ADRs | None |\n\n## Goal\n",
                state.name()
            ),
        }
    }

    /// `file` with a Blocks row after its Depends on row, as todo files had before the board left git.
    fn with_blocks(mut file: TodoFile, blocks: &str) -> TodoFile {
        file.text = file
            .text
            .replace("| ADRs |", &format!("| Blocks | {blocks} |\n| ADRs |"));
        file
    }

    /// A consistent graph: A1 (done) ← B1 (ongoing) ← B2 (ready), and X1 (ready, no deps).
    fn consistent() -> Vec<TodoFile> {
        vec![
            todo(State::Ready, "B2", "[B1](../ongoing/B1-x.md)"),
            todo(State::Ready, "X1", "None"),
            todo(State::Ongoing, "B1", "[A1](../done/A1-x.md)"),
            todo(State::Done, "A1", "None"),
        ]
    }

    fn generated(files: &[TodoFile]) -> Generated {
        generate(files).unwrap()
    }

    fn problems(files: &[TodoFile]) -> Vec<String> {
        generate(files).unwrap_err()
    }

