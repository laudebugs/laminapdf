//! `cargo xtask todos [--check]`: checks the todo files and builds the todo board from them.
//!
//! Each todo's dependencies are the explicit links in its **Depends on** field
//! (`[B2a](../done/B2a-….md), …` or `None`); nothing is guessed from prose. The graph must be
//! consistent: **Status** matches the state folder, the file name starts with the ID, every
//! dependency exists, there are no cycles, and a done todo depends only on done ones.
//!
//! Only what people write is committed. The board (the counts, "Can start now", one table per
//! plan) and what each todo blocks are derived from many todos at once, so a committed copy would
//! change in every pull request that moves a todo, and each merge would make the other open pull
//! requests conflict on it. Instead, `cargo xtask todos` prints the board's lists and writes the
//! whole board to [`BOARD`], outside git. It also points each Depends on link at the folder its
//! todo is in now and deletes any Blocks row. `--check` changes nothing and fails on a link to an
//! old folder, on a Blocks row, and on a `docs/todos/README.md` that links to a todo file, which
//! is how a merge would bring a stale board back.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::tracked::Tracked;

/// A todo's state, which is also the folder it lives in.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum State {
    Ready,
    Ongoing,
    Done,
}

impl State {
    pub(crate) const ALL: [Self; 3] = [Self::Ready, Self::Ongoing, Self::Done];

    pub(crate) fn name(self) -> &'static str {
        match self {
            Self::Ready => "ready",
            Self::Ongoing => "ongoing",
            Self::Done => "done",
        }
    }
}

/// The ID letters in board order: plan sections in the order the board lists them.
pub(crate) const SECTIONS: [(char, &str); 12] = [
    ('A', "Architecture — Round A"),
    ('B', "Library — Round B"),
    ('L', "Shareable libraries — Rounds L1–L6"),
    ('C', "Web reader — Round C"),
    ('W', "Website — Round W"),
    ('D', "Desktop reader — Round D"),
    ('U', "UI/UX — Round U"),
    ('H', "Hosted service"),
    ('E', "Editor — Rounds E1–E18"),
    ('P', "Publishing (later)"),
    ('Q', "Docs and code quality — Round Q"),
    ('X', "Cross-cutting"),
];

/// The order IDs sort in (`order_key` in the original board script): letter, number, suffix.
const LETTER_ORDER: &str = "ABLCWDUEHPQX";

/// Where `cargo xtask todos` writes the board, relative to the root (`target/` is ignored by git).
pub(crate) const BOARD: &str = "target/todos/board.md";

/// `docs/todos/` as a link from [`BOARD`].
const TODOS_FROM_BOARD: &str = "../../docs/todos/";

/// The board's opening, before the counts.
fn board_header() -> String {
    format!(
        "# Todo board\n\nGenerated by `cargo xtask todos` from the todo files, and never committed. \
         How the folders and the workflow work: [`docs/todos/README.md`]({TODOS_FROM_BOARD}README.md).\n\n"
    )
}

/// What the board's "Can start now" holds.
const START_NOW: &str =
    "Ready todos whose dependencies are all done (an open PR may already have claimed one: check `gh pr list`)";

/// The board's "Ongoing" when no todo is in `ongoing/`.
const NONE_ONGOING: &str = "Nothing in `ongoing/`: claims live on the open PRs' branches (`gh pr list`).";

/// One todo file as read from disk.
#[derive(Debug, Clone)]
pub(crate) struct TodoFile {
    pub(crate) state: State,
    /// File name, e.g. `X1-docs-link-checker.md`.
    pub(crate) file: String,
    pub(crate) text: String,
}

/// A parsed todo.
#[derive(Debug)]
pub(crate) struct Todo {
    pub(crate) id: String,
    pub(crate) state: State,
    pub(crate) file: String,
    pub(crate) title: String,
    pub(crate) deps: Vec<String>,
}

/// What the todo files should contain (same order as the input), and the board built from them.
#[derive(Debug)]
pub(crate) struct Generated {
    pub(crate) texts: Vec<String>,
    /// The whole board, with links relative to [`BOARD`].
    pub(crate) board: String,
    /// "Can start now" and "Ongoing" for the terminal, with paths from the root.
    pub(crate) lists: String,
    /// A one-line summary for the terminal.
    pub(crate) summary: String,
}

/// Checks the todo files under `root`, then (unless `check`) rewrites the stale ones and writes
/// the board to [`BOARD`].
pub(crate) fn run(root: &Path, check: bool) -> Result<()> {
    let dir = root.join("docs/todos");
    let files = load(root, &Tracked::from_git(root)?)?;
    let generated = match generate(&files) {
        Ok(generated) => generated,
        Err(problems) => {
            for problem in &problems {
                eprintln!("docs/todos: {problem}");
            }
            bail!(
                "{} problem(s) in the todo files; fix them, then run `cargo xtask todos`",
                problems.len()
            );
        }
    };
    let readme = fs::read_to_string(dir.join("README.md")).context("reading docs/todos/README.md")?;
    if let Some(target) = todo_link(&readme) {
        bail!(
            "docs/todos/README.md links to the todo file {target}, but the board is never committed: \
             take main's README.md and run `cargo xtask todos` to see the board"
        );
    }
    println!("todos: {}", generated.summary);
    let stale = stale_files(&files, &generated);
    if check {
        if stale.is_empty() {
            println!("todos: the todo files are up to date");
            return Ok(());
        }
        for (path, reason) in &stale {
            eprintln!("stale: docs/todos/{path}: {reason}");
        }
        bail!("the todo files are stale: run `cargo xtask todos` and commit the result");
    }
    for (todo, text) in files.iter().zip(&generated.texts) {
        if *text != todo.text {
            let path = dir.join(todo.state.name()).join(&todo.file);
            fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
        }
    }
    for (path, _) in &stale {
        println!("updated docs/todos/{path}");
    }
    let board_path = root.join(BOARD);
    if let Some(parent) = board_path.parent() {
        fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
    }
    fs::write(&board_path, &generated.board).with_context(|| format!("writing {}", board_path.display()))?;
    print!("{}", generated.lists);
    println!("todos: the whole board, with what each todo depends on and blocks, is in {BOARD}");
    Ok(())
}

/// Every tracked `*.md` in the state folders, by state then file name. Untracked drafts are
/// left out, as GitHub never shows them: `git add` a new todo before running `cargo xtask todos`.
pub(crate) fn load(root: &Path, tracked: &Tracked) -> Result<Vec<TodoFile>> {
    let mut files = Vec::new();
    for state in State::ALL {
        let folder = Path::new("docs/todos").join(state.name());
        for path in tracked.files().filter(|path| path.parent() == Some(folder.as_path())) {
            let Some(file) = path.file_name().and_then(|name| name.to_str()) else {
                continue;
            };
            if Path::new(file).extension().is_none_or(|ext| ext != "md") {
                continue;
            }
            let text = fs::read_to_string(root.join(path)).with_context(|| format!("reading {}", path.display()))?;
            files.push(TodoFile {
                state,
                file: file.to_owned(),
                text,
            });
        }
    }
    Ok(files)
}

/// The todo files (paths relative to `docs/todos`) whose committed text differs from the
/// generated one, each with every reason that applies.
pub(crate) fn stale_files(files: &[TodoFile], generated: &Generated) -> Vec<(String, String)> {
    files
        .iter()
        .zip(&generated.texts)
        .filter(|(todo, text)| todo.text != **text)
        .map(|(todo, text)| {
            let mut reasons = Vec::new();
            if field(&todo.text, "Blocks").is_some() {
                reasons.push("a Blocks row (the board lists what each todo blocks)");
            }
            let depends_on = |text: &str| {
                text.lines()
                    .find(|line| row_value(line, "Depends on").is_some())
                    .map(str::to_owned)
            };
            if depends_on(&todo.text) != depends_on(text) {
                reasons.push("Depends on isn't the links `cargo xtask todos` writes (current folders, board order)");
            }
            if reasons.is_empty() {
                reasons.push("differs from what `cargo xtask todos` writes");
            }
            (format!("{}/{}", todo.state.name(), todo.file), reasons.join("; "))
        })
        .collect()
}

/// The first link in `readme` to a todo file (`ready/X1-….md`, `./done/X1-….md#goal`, for any
/// state), if there is one. The folders' README describes the board but never lists todos: a
/// list there goes stale.
pub(crate) fn todo_link(readme: &str) -> Option<&str> {
    readme.match_indices("](").find_map(|(at, _)| {
        let (target, _) = readme.get(at + 2..)?.split_once(')')?;
        let path = target.split_once('#').map_or(target, |(path, _)| path);
        let path = Path::new(path.strip_prefix("./").unwrap_or(path));
        let folder = path.parent()?.to_str()?;
        let in_a_state_folder = State::ALL.iter().any(|state| state.name() == folder);
        (in_a_state_folder && path.extension().is_some_and(|ext| ext == "md")).then_some(target)
    })
}

/// The todos of `files`, in the files' order, once the graph is consistent: well-formed IDs and
/// fields, Status matching the folder, no duplicate IDs, known dependencies, no cycles, and done
/// todos depending only on done ones. Otherwise every problem found.
pub(crate) fn checked(files: &[TodoFile]) -> Result<Vec<Todo>, Vec<String>> {
    let mut problems = Vec::new();
    let todos: Vec<Todo> = files.iter().filter_map(|f| parse(f, &mut problems)).collect();
    if !problems.is_empty() {
        return Err(problems);
    }
    let by_id: BTreeMap<&str, &Todo> = todos.iter().map(|t| (t.id.as_str(), t)).collect();
    if by_id.len() != todos.len() {
        for (i, todo) in todos.iter().enumerate() {
            if todos.iter().take(i).any(|earlier| earlier.id == todo.id) {
                problems.push(format!("duplicate ID {} ({})", todo.id, todo.file));
            }
        }
        return Err(problems);
    }
    for todo in &todos {
        for dep in &todo.deps {
            match by_id.get(dep.as_str()) {
                None => problems.push(format!("{}: unknown dependency ID {dep:?}", todo.id)),
                Some(d) if todo.state == State::Done && d.state != State::Done => {
                    problems.push(format!("{} is done but depends on {dep} ({})", todo.id, d.state.name()));
                }
                Some(_) => {}
            }
        }
    }
    if !problems.is_empty() {
        return Err(problems);
    }
    problems.extend(cycles(&todos, &by_id));
    if !problems.is_empty() {
        return Err(problems);
    }
    Ok(todos)
}

/// The board's "Can start now": the ready todos whose dependencies are all done, in board order.
/// `by_id` maps each of `todos` by its ID.
pub(crate) fn startable<'a>(todos: &'a [Todo], by_id: &BTreeMap<&str, &Todo>) -> Vec<&'a Todo> {
    let mut startable: Vec<&Todo> = todos
        .iter()
        .filter(|t| {
            t.state == State::Ready
                && t.deps
                    .iter()
                    .all(|d| by_id.get(d.as_str()).is_some_and(|d| d.state == State::Done))
        })
        .collect();
    startable.sort_by_key(|t| order_key(&t.id));
    startable
}

/// Checks the todo graph and generates the files and the board, or lists every problem found.
pub(crate) fn generate(files: &[TodoFile]) -> Result<Generated, Vec<String>> {
    let todos = checked(files)?;
    let by_id: BTreeMap<&str, &Todo> = todos.iter().map(|t| (t.id.as_str(), t)).collect();
    let mut blocks: BTreeMap<&str, Vec<&Todo>> = BTreeMap::new();
    for todo in &todos {
        for dep in &todo.deps {
            blocks.entry(dep.as_str()).or_default().push(todo);
        }
    }
    for blocked in blocks.values_mut() {
        blocked.sort_by_key(|t| order_key(&t.id));
    }
    let mut problems = Vec::new();
    let mut texts = Vec::with_capacity(files.len());
    for (file, todo) in files.iter().zip(&todos) {
        let links: Vec<String> = sorted_deps(todo, &by_id)
            .into_iter()
            .map(|to| relative_link(todo, to))
            .collect();
        let links = if links.is_empty() {
            "None".to_owned()
        } else {
            links.join(", ")
        };
        match replace_field(&file.text, "Depends on", &links) {
            Some(text) => texts.push(without_field(&text, "Blocks")),
            None => problems.push(format!("{}: missing a `| Depends on | … |` row", todo.id)),
        }
    }
    if !problems.is_empty() {
        return Err(problems);
    }
    let (board, lists, summary) = board(&todos, &by_id, &blocks);
    Ok(Generated {
        texts,
        board,
        lists,
        summary,
    })
}

/// The ID, title and dependencies of one todo file; problems are pushed to `problems`.
fn parse(file: &TodoFile, problems: &mut Vec<String>) -> Option<Todo> {
    let path = format!("{}/{}", file.state.name(), file.file);
    let Some(id) = field(&file.text, "ID").and_then(|v| v.strip_prefix('`')?.strip_suffix('`')) else {
        problems.push(format!("{path}: no `| ID | `…` |` row"));
        return None;
    };
    if !is_todo_id(id) {
        problems.push(format!(
            "{path}: ID {id:?} is not a letter from {LETTER_ORDER}, a number and an optional suffix"
        ));
        return None;
    }
    if !file.file.starts_with(&format!("{id}-")) {
        problems.push(format!("{path}: file name must start with its ID `{id}-`"));
    }
    let expected = format!("`{}`", file.state.name());
    match field(&file.text, "Status") {
        // A note may follow the state: `` `ready` — blocked on … ``.
        Some(status) if status == expected || status.starts_with(&format!("{expected} ")) => {}
        Some(status) => problems.push(format!(
            "{path}: Status {status} does not match its folder (expected {expected}); move the file or fix the Status"
        )),
        None => problems.push(format!("{path}: no `| Status | … |` row")),
    }
    let Some(heading) = file.text.lines().find_map(|line| line.strip_prefix("# ")) else {
        problems.push(format!("{path}: no `# <ID> — <title>` heading"));
        return None;
    };
    let title = match heading.split_once(" — ") {
        Some((prefix, rest)) if !prefix.is_empty() && !prefix.contains(char::is_whitespace) => rest,
        _ => heading,
    };
    let Some(raw) = field(&file.text, "Depends on").map(str::trim) else {
        problems.push(format!("{path}: no `| Depends on | … |` row"));
        return None;
    };
    let deps = if raw == "None" {
        Vec::new()
    } else if let Some(links) = parse_links(raw) {
        let mut deps: Vec<String> = Vec::new();
        for (dep, _target) in links {
            if !deps.iter().any(|d| d == dep) {
                deps.push(dep.to_owned());
            }
        }
        deps
    } else {
        problems.push(format!(
            "{id}: Depends on must be comma-separated links or None: {raw:?}"
        ));
        Vec::new()
    };
    Some(Todo {
        id: id.to_owned(),
        state: file.state,
        file: file.file.clone(),
        title: title.to_owned(),
        deps,
    })
}

/// The value of a `| <name> | <value> |` header row (the first one), trimmed.
fn field<'a>(text: &'a str, name: &str) -> Option<&'a str> {
    text.lines().find_map(|line| row_value(line, name))
}

/// The trimmed value when `line` (without its `\n`) is a `| <name> | <value> |` row. [`field`],
/// [`replace_field`] and [`without_field`] all match rows with it, so they never disagree on one.
fn row_value<'a>(line: &'a str, name: &str) -> Option<&'a str> {
    let rest = line
        .trim_end()
        .strip_prefix("| ")?
        .strip_prefix(name)?
        .strip_prefix(" |")?;
    Some(rest.strip_suffix('|')?.trim())
}

/// `text` with the first `| <name> | … |` row's value replaced; `None` when there is no such row.
fn replace_field(text: &str, name: &str, value: &str) -> Option<String> {
    let mut out = String::with_capacity(text.len());
    let mut replaced = false;
    for line in text.split_inclusive('\n') {
        let (body, newline) = line.strip_suffix('\n').map_or((line, ""), |body| (body, "\n"));
        if !replaced && row_value(body, name).is_some() {
            let cr = if body.ends_with('\r') { "\r" } else { "" };
            let _ = write!(out, "| {name} | {value} |{cr}{newline}");
            replaced = true;
        } else {
            out.push_str(line);
        }
    }
    replaced.then_some(out)
}

/// `text` without any `| <name> | … |` row (unchanged when there is none).
fn without_field(text: &str, name: &str) -> String {
    text.split_inclusive('\n')
        .filter(|line| row_value(line.strip_suffix('\n').unwrap_or(line), name).is_none())
        .collect()
}

/// `[ID](target)` links separated by commas and spaces, or `None` if anything else is there.
fn parse_links(raw: &str) -> Option<Vec<(&str, &str)>> {
    let mut links = Vec::new();
    let mut rest = raw;
    loop {
        rest = rest.trim_start_matches([' ', ',']);
        if rest.is_empty() {
            break;
        }
        let (id, after) = rest.strip_prefix('[')?.split_once("](")?;
        let (target, after) = after.split_once(')')?;
        if !looks_like_id(id) || target.is_empty() {
            return None;
        }
        links.push((id, target));
        rest = after;
    }
    (!links.is_empty()).then_some(links)
}

/// An uppercase letter, digits and an optional lowercase suffix (`B2a`).
fn looks_like_id(id: &str) -> bool {
    let mut chars = id.chars();
    if !chars.next().is_some_and(|c| c.is_ascii_uppercase()) {
        return false;
    }
    let rest = chars.as_str();
    let digits = rest.trim_end_matches(|c: char| c.is_ascii_lowercase());
    rest.len() - digits.len() <= 1 && !digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit())
}

/// A well-formed ID whose letter is one of the board's sections.
fn is_todo_id(id: &str) -> bool {
    looks_like_id(id) && id.chars().next().is_some_and(|c| LETTER_ORDER.contains(c))
}

/// An ID's letter, round number and suffix (`B2a` → `('B', 2, "a")`), or `None` if it isn't one.
pub(crate) fn id_parts(id: &str) -> Option<(char, u64, &str)> {
    if !looks_like_id(id) {
        return None;
    }
    let mut chars = id.chars();
    let letter = chars.next()?;
    let rest = chars.as_str();
    let digits = rest.trim_end_matches(|c: char| c.is_ascii_lowercase());
    Some((letter, digits.parse().ok()?, rest.get(digits.len()..)?))
}

/// Sort key: section letter, round number, suffix.
pub(crate) fn order_key(id: &str) -> (usize, u64, String) {
    match id_parts(id) {
        Some((letter, round, suffix)) => (
            LETTER_ORDER.find(letter).unwrap_or(usize::MAX),
            round,
            suffix.to_owned(),
        ),
        None => (usize::MAX, u64::MAX, String::new()),
    }
}

/// Every dependency cycle, as `cycle: A -> B -> A`.
fn cycles(todos: &[Todo], by_id: &BTreeMap<&str, &Todo>) -> Vec<String> {
    #[derive(Clone, Copy, PartialEq)]
    enum Mark {
        InProgress,
        Finished,
    }
    fn visit<'a>(
        todo: &'a Todo,
        by_id: &BTreeMap<&str, &'a Todo>,
        marks: &mut BTreeMap<&'a str, Mark>,
        stack: &mut Vec<&'a str>,
        found: &mut Vec<String>,
    ) {
        marks.insert(&todo.id, Mark::InProgress);
        stack.push(&todo.id);
        for dep in &todo.deps {
            let Some(next) = by_id.get(dep.as_str()) else { continue };
            match marks.get(next.id.as_str()) {
                Some(Mark::InProgress) => found.push(format!("cycle: {} -> {}", stack.join(" -> "), next.id)),
                Some(Mark::Finished) => {}
                None => visit(next, by_id, marks, stack, found),
            }
        }
        stack.pop();
        marks.insert(&todo.id, Mark::Finished);
    }

    let mut marks = BTreeMap::new();
    let mut found = Vec::new();
    for todo in todos {
        if !marks.contains_key(todo.id.as_str()) {
            visit(todo, by_id, &mut marks, &mut Vec::new(), &mut found);
        }
    }
    found
}

/// A link from one todo file to another: `./X.md` in the same folder, else `../<state>/X.md`.
fn relative_link(from: &Todo, to: &Todo) -> String {
    if from.state == to.state {
        format!("[{}](./{})", to.id, to.file)
    } else {
        format!("[{}](../{}/{})", to.id, to.state.name(), to.file)
    }
}

/// `todo`'s dependencies, in board order.
fn sorted_deps<'a>(todo: &Todo, by_id: &BTreeMap<&str, &'a Todo>) -> Vec<&'a Todo> {
    let mut deps: Vec<&Todo> = todo
        .deps
        .iter()
        .filter_map(|d| by_id.get(d.as_str()).copied())
        .collect();
    deps.sort_by_key(|d| order_key(&d.id));
    deps
}

/// A link from the board ([`BOARD`]) to a todo.
fn board_link(todo: &Todo) -> String {
    format!("[{}]({TODOS_FROM_BOARD}{}/{})", todo.id, todo.state.name(), todo.file)
}

/// Board links to `todos`, comma-separated, or `—` when there are none.
fn board_links(todos: &[&Todo]) -> String {
    if todos.is_empty() {
        return "—".to_owned();
    }
    let links: Vec<String> = todos.iter().map(|t| board_link(t)).collect();
    links.join(", ")
}

/// The board text, its lists for the terminal and a one-line summary. `blocks` maps an ID to the
/// todos that depend on it, in board order.
fn board(
    todos: &[Todo],
    by_id: &BTreeMap<&str, &Todo>,
    blocks: &BTreeMap<&str, Vec<&Todo>>,
) -> (String, String, String) {
    let mut sorted: Vec<&Todo> = todos.iter().collect();
    sorted.sort_by_key(|t| order_key(&t.id));
    let count = |state: State| todos.iter().filter(|t| t.state == state).count();
    let (ongoing, ready, done) = (count(State::Ongoing), count(State::Ready), count(State::Done));
    let startable = startable(todos, by_id);
    let in_progress: Vec<&Todo> = sorted.iter().copied().filter(|t| t.state == State::Ongoing).collect();

    let mut out = board_header();
    let _ = writeln!(
        out,
        "**{ongoing} ongoing · {ready} ready · {done} done** ({} total).\n",
        todos.len()
    );
    let _ = writeln!(out, "## Can start now\n\n{START_NOW}:\n");
    for todo in &startable {
        let _ = writeln!(out, "- {}: {}", board_link(todo), todo.title);
    }
    out.push_str("\n## Ongoing\n\n");
    if in_progress.is_empty() {
        let _ = writeln!(out, "{NONE_ONGOING}");
    }
    for todo in &in_progress {
        let _ = writeln!(out, "- {}: {}", board_link(todo), todo.title);
    }
    out.push('\n');
    write_tables(&mut out, &sorted, by_id, blocks);

    let ids: Vec<&str> = startable.iter().map(|t| t.id.as_str()).collect();
    let summary = format!(
        "{} todos ({ongoing} ongoing, {ready} ready, {done} done); can start now: {}",
        todos.len(),
        if ids.is_empty() {
            "none".to_owned()
        } else {
            ids.join(", ")
        }
    );
    (out, terminal_lists(&startable, &in_progress), summary)
}

/// One table per plan section, the todos of `sorted` in board order with what they depend on and
/// what they block.
fn write_tables(
    out: &mut String,
    sorted: &[&Todo],
    by_id: &BTreeMap<&str, &Todo>,
    blocks: &BTreeMap<&str, Vec<&Todo>>,
) {
    for (letter, heading) in SECTIONS {
        let group: Vec<&&Todo> = sorted.iter().filter(|t| t.id.starts_with(letter)).collect();
        if group.is_empty() {
            continue;
        }
        let _ = write!(
            out,
            "## {heading}\n\n| ID | Todo | State | Depends on | Blocks |\n| --- | --- | --- | --- | --- |\n"
        );
        for todo in group {
            let blocked = blocks.get(todo.id.as_str()).map_or(&[][..], Vec::as_slice);
            let _ = writeln!(
                out,
                "| {} | [{}]({TODOS_FROM_BOARD}{}/{}) | {} | {} | {} |",
                todo.id,
                todo.title,
                todo.state.name(),
                todo.file,
                todo.state.name(),
                board_links(&sorted_deps(todo, by_id)),
                board_links(blocked)
            );
        }
        out.push('\n');
    }
}

/// "Can start now" and "Ongoing" as the terminal shows them, each todo with its path from the root.
fn terminal_lists(startable: &[&Todo], in_progress: &[&Todo]) -> String {
    let list = |out: &mut String, todos: &[&Todo]| {
        for todo in todos {
            let _ = writeln!(
                out,
                "- {}: {} (docs/todos/{}/{})",
                todo.id,
                todo.title,
                todo.state.name(),
                todo.file
            );
        }
    };
    let mut out = format!("\n{START_NOW}:\n");
    list(&mut out, startable);
    out.push_str("\nOngoing:\n");
    if in_progress.is_empty() {
        let _ = writeln!(out, "{NONE_ONGOING}");
    }
    list(&mut out, in_progress);
    out.push('\n');
    out
}

