//! `cargo xtask gen boundary [--check]`: the TypeScript side of the lists that cross the WASM
//! boundary, read from the Rust source that defines them (Q2l), so neither side keeps a copy:
//!
//! - `packages/sdk/src/generated/builder-enums.ts`: the names of fill rules, line caps and
//!   joins, blend modes, artifact kinds and table scopes (laminapdf-wasm's name tables in
//!   `src/build_dto.rs`) and of the standard structure types (`TagKind::as_str` in
//!   laminapdf-build), each a list and its union type;
//! - `packages/render-hayro/src/generated/version.ts`: `HAYRO_VERSION`, the workspace's hayro pin.
//!
//! It reads source text, not a build, so `cargo xtask check docs` runs `--check`. The parser
//! accepts only the literal shapes those files use and fails, naming the item, on anything else.

use std::fmt::Write as _;
use std::fs;

use anyhow::{Context, Result, bail};

use crate::workspace::Workspace;

const HEADER: &str = "// @generated by cargo xtask gen boundary. DO NOT EDIT.";

const DTO: &str = "crates/laminapdf-wasm/src/build_dto.rs";
const TAG_KIND: &str = "crates/laminapdf-build/src/tag/mod.rs";
const CARGO_TOML: &str = "Cargo.toml";

const SDK_ENUMS: &str = "packages/sdk/src/generated/builder-enums.ts";
const HAYRO_VERSION: &str = "packages/render-hayro/src/generated/version.ts";

/// One list: the Rust table it comes from (the TS list has the same name), its TS union type
/// and that type's doc comment.
struct List {
    table: &'static str,
    union: &'static str,
    doc: &'static str,
}

/// laminapdf-wasm's name tables, in the order the TS module lists them.
const LISTS: [List; 6] = [
    List {
        table: "FILL_RULES",
        union: "FillRule",
        doc: "How a filled or clipped path decides what is inside.",
    },
    List {
        table: "LINE_CAPS",
        union: "LineCap",
        doc: "How open line ends are drawn.",
    },
    List {
        table: "LINE_JOINS",
        union: "LineJoin",
        doc: "How corners are drawn.",
    },
    List {
        table: "BLEND_MODES",
        union: "BlendMode",
        doc: "Blend modes (`/BM`), camelCase.",
    },
    List {
        table: "ARTIFACT_KINDS",
        union: "ArtifactKind",
        doc: "What kind of artifact (content outside the logical structure).",
    },
    List {
        table: "TABLE_SCOPES",
        union: "TableScope",
        doc: "Which header cells a `TH` heads (`/Scope`).",
    },
];

/// `cargo xtask gen boundary [--check]`.
pub(crate) fn generate(ws: &Workspace, check: bool) -> Result<()> {
    let read = |path: &str| fs::read_to_string(ws.root.join(path)).with_context(|| format!("reading {path}"));
    let outputs = [
        (SDK_ENUMS, render_sdk(&read(DTO)?, &read(TAG_KIND)?)?),
        (HAYRO_VERSION, render_hayro(&read(CARGO_TOML)?)?),
    ];
    let stale: Vec<&str> = outputs
        .iter()
        .filter(|(path, text)| fs::read_to_string(ws.root.join(path)).ok().as_deref() != Some(text.as_str()))
        .map(|(path, _)| *path)
        .collect();
    if check {
        if !stale.is_empty() {
            bail!(
                "generated from the Rust source and stale: {}\nrun `cargo xtask gen boundary`",
                stale.join(", ")
            );
        }
        crate::step("gen boundary --check: every list shared with TypeScript is up to date");
        return Ok(());
    }
    for (path, text) in &outputs {
        if stale.contains(path) {
            let full = ws.root.join(path);
            if let Some(dir) = full.parent() {
                fs::create_dir_all(dir)?;
            }
            fs::write(&full, text).with_context(|| format!("writing {path}"))?;
            println!("wrote {path}");
        }
    }
    if stale.is_empty() {
        println!("every list shared with TypeScript is up to date");
    }
    Ok(())
}

/// The names of `const NAME: [(&str, Type); N] = [("name", Type::Variant), …];` in `source`.
fn name_table(source: &str, name: &str) -> Result<Vec<String>> {
    let head = format!("const {name}: [(&str, ");
    let start = source.find(&head).with_context(|| format!("{DTO}: no table {name}"))?;
    let rest = &source[start + head.len()..];
    let (ty, rest) = rest
        .split_once("); ")
        .with_context(|| format!("{DTO}: {name}'s type"))?;
    let (len, rest) = rest
        .split_once("] = [")
        .with_context(|| format!("{DTO}: {name}'s length"))?;
    let len: usize = len.trim().parse().with_context(|| format!("{DTO}: {name}'s length"))?;
    let (body, _) = rest
        .split_once("];")
        .with_context(|| format!("{DTO}: {name} is not closed"))?;
    let entry = format!("\", {ty}::");
    let names: Vec<String> = body
        .split("(\"")
        .skip(1)
        .map(|item| item.split_once(&entry).map(|(n, _)| n.to_owned()))
        .collect::<Option<_>>()
        .with_context(|| format!("{DTO}: {name} has an entry that isn't (\"name\", {ty}::Variant)"))?;
    if names.len() != len {
        bail!("{DTO}: {name} declares {len} entries and lists {}", names.len());
    }
    Ok(names)
}

/// The names `TagKind::as_str` returns, in its order (`Self::X => "X",` arms).
fn tag_names(source: &str) -> Result<Vec<String>> {
    let imp = source
        .find("impl TagKind {")
        .with_context(|| format!("{TAG_KIND}: no impl TagKind"))?;
    let rest = &source[imp..];
    let start = rest
        .find("pub const fn as_str(self) -> &'static str {")
        .with_context(|| format!("{TAG_KIND}: no TagKind::as_str"))?;
    let body = &rest[start..];
    let end = body
        .find("\n    }\n")
        .with_context(|| format!("{TAG_KIND}: TagKind::as_str is not closed"))?;
    let names: Vec<String> = body[..end]
        .lines()
        .filter_map(|l| l.trim().strip_prefix("Self::"))
        .map(|arm| {
            arm.split_once(" => \"")
                .and_then(|(_, n)| n.strip_suffix("\","))
                .map(str::to_owned)
        })
        .collect::<Option<_>>()
        .with_context(|| format!("{TAG_KIND}: a TagKind::as_str arm isn't `Self::X => \"X\",`"))?;
    if names.is_empty() {
        bail!("{TAG_KIND}: TagKind::as_str has no arms");
    }
    Ok(names)
}

/// `export const LIST = [...] as const;` and its union type.
fn ts_list(out: &mut String, list: &str, ty: &str, doc: &str, names: &[String]) {
    let _ = writeln!(out, "/** Every {ty}, as the WASM module names it. */");
    let _ = writeln!(out, "export const {list} = [");
    for n in names {
        let _ = writeln!(out, "  \"{n}\",");
    }
    let _ = writeln!(out, "] as const;\n");
    let _ = writeln!(out, "/** {doc} */");
    let _ = writeln!(out, "export type {ty} = (typeof {list})[number];\n");
}

fn render_sdk(dto: &str, tag_kind: &str) -> Result<String> {
    let mut out = format!(
        "{HEADER}\n// From laminapdf-wasm's name tables and laminapdf-build's TagKind::as_str; `cargo xtask check docs` fails when it is stale.\n\n"
    );
    for l in &LISTS {
        ts_list(&mut out, l.table, l.union, l.doc, &name_table(dto, l.table)?);
    }
    ts_list(
        &mut out,
        "TAG_NAMES",
        "TagName",
        "A standard structure type (ISO 32000-1 §14.8.4).",
        &tag_names(tag_kind)?,
    );
    Ok(out.trim_end().to_owned() + "\n")
}

/// `HAYRO_VERSION` from the workspace's `hayro = { version = "=x.y.z" }`.
fn render_hayro(cargo_toml: &str) -> Result<String> {
    let manifest: toml::Value = toml::from_str(cargo_toml).context("Cargo.toml is not TOML")?;
    let pin = manifest
        .get("workspace")
        .and_then(|w| w.get("dependencies"))
        .and_then(|d| d.get("hayro"))
        .and_then(|h| h.get("version"))
        .and_then(toml::Value::as_str)
        .context("Cargo.toml: no [workspace.dependencies] hayro version")?;
    let Some(version) = pin.strip_prefix('=') else {
        bail!("Cargo.toml: hayro is pinned as {pin:?}, not an exact `=x.y.z`");
    };
    Ok(format!(
        "{HEADER}\n// From the workspace's hayro pin in Cargo.toml.\n\n/** The pinned hayro version (the workspace's `={version}`). */\nexport const HAYRO_VERSION = \"{version}\";\n"
    ))
}

#[cfg(test)]
mod tests {
    use super::{name_table, tag_names};

    #[test]
    fn name_table_should_read_names_in_order() {
        let src = "pub(crate) const LINE_CAPS: [(&str, LineCap); 2] = [\n    (\"butt\", LineCap::Butt),\n    (\"round\", LineCap::Round),\n];";
        assert_eq!(name_table(src, "LINE_CAPS").unwrap(), ["butt", "round"]);
    }

    #[test]
    fn name_table_should_refuse_a_wrong_length() {
        let src = "const A: [(&str, X); 3] = [(\"a\", X::A), (\"b\", X::B)];";
        assert!(name_table(src, "A").is_err());
    }

    #[test]
    fn name_table_should_refuse_an_entry_of_another_shape() {
        let src = "const A: [(&str, X); 2] = [(\"a\", X::A), (\"b\", Y::B)];";
        assert!(name_table(src, "A").is_err());
    }

    #[test]
    fn tag_names_should_read_the_as_str_arms() {
        let src = "impl TagKind {\n    pub const fn as_str(self) -> &'static str {\n        match self {\n            Self::P => \"P\",\n            Self::H1 => \"H1\",\n        }\n    }\n}\n";
        assert_eq!(tag_names(src).unwrap(), ["P", "H1"]);
    }
}
