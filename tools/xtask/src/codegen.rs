/// The header of every generated source file (code organisation §9).
const HEADER: &str = "// @generated by cargo xtask gen codes. DO NOT EDIT.";

/// The input and its schema.
const CODES: &str = "fixtures/codes.json";
const CODES_SCHEMA: &str = "fixtures/codes.schema.json";

/// The outputs.
const RUST: &str = "crates/laminapdf-syntax/src/generated/codes.rs";
const RUST_EXPLAIN: &str = "crates/laminapdf/src/generated/explain.rs";
const TS: &str = "packages/sdk/src/generated/codes.ts";
const TS_EXPLAIN: &str = "packages/sdk/src/generated/explain.ts";
const SCHEMAS: [&str; 2] = [
    "packages/sdk/schemas/error.schema.json",
    "crates/laminapdf/schemas/error.schema.json",
];
const ERRORS_README: &str = "docs/errors/README.md";

/// The line in `docs/errors/README.md` after which everything is generated.
const README_MARKER: &str = "<!-- @generated below by cargo xtask gen codes. DO NOT EDIT. -->";

/// The code groups of `codes.json`, in the order every output lists them, with the heading of
/// their table. A group missing here fails the generator, so a new group gets a title.
const GROUPS: [(&str, &str); 11] = [
    ("warnings", "Warnings"),
    ("errors", "Errors"),
    ("opErrors", "Op errors"),
    ("saveErrors", "Save errors"),
    ("textErrors", "Text errors (`laminapdf-text`)"),
    ("textWarnings", "Text warnings (`laminapdf-text`)"),
    ("buildErrors", "Build errors (`laminapdf-build`)"),
    ("renderErrors", "Render errors (`laminapdf-render`)"),
    ("facadeErrors", "Façade errors (`laminapdf`)"),
    ("bindingErrors", "Binding errors (`laminapdf-wasm`)"),
    ("packageErrors", "Package errors (`@laminapdf/sdk`)"),
];

/// Codes of other groups that `@laminapdf/sdk` raises itself; each must be listed in `codes.json`.
const ALSO_RAISED_BY_TS: [&str; 6] = [
    "builder-finished",
    "cancelled",
    "disposed",
    "invalid-argument",
    "nested-transaction",
    "no-transaction",
];

/// One code of `codes.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Entry {
    group: String,
    code: String,
    kind: String,
    summary: String,
    hint: String,
}

impl Entry {
    fn is_warning(&self) -> bool {
        is_warning_group(&self.group)
    }

    /// Raised only by `@laminapdf/sdk`, so absent from the Rust enums.
    fn is_ts_only(&self) -> bool {
        TS_ONLY_GROUPS.contains(&self.group.as_str())
    }
}

/// `codes.json`, validated and read.
#[derive(Debug)]
struct Codes {
    /// `docsUrl.base` and `docsUrl.suffix`.
    docs_base: String,
    docs_suffix: String,
    /// The kinds, from the schema's `$defs.kind.enum` (ADR 0026 §2).
    kinds: Vec<String>,
    limits: Vec<String>,
    /// Every code, groups in [`GROUPS`] order, codes in file order.
    entries: Vec<Entry>,
}

/// `cargo xtask gen codes [--check]`.
pub(crate) fn codes(ws: &Workspace, check: bool) -> Result<()> {
    let outputs = render_all(&ws.root)?;
    write_outputs(ws, &outputs, check, "gen codes", CODES)
}

/// Writes each stale output, or with `check` fails naming them: what both generators do once
/// they have rendered their files in memory from `source`.
fn write_outputs(ws: &Workspace, outputs: &[(String, String)], check: bool, command: &str, source: &str) -> Result<()> {
    let stale: Vec<&str> = outputs
        .iter()
        .filter(|(path, text)| fs::read_to_string(ws.root.join(path)).ok().as_deref() != Some(text.as_str()))
        .map(|(path, _)| path.as_str())
        .collect();
    if check {
        if !stale.is_empty() {
            bail!(
                "generated from {source} and stale: {}\nrun `cargo xtask {command}`",
                stale.join(", ")
            );
        }
        crate::step(&format!(
            "{command} --check: every file generated from {source} is up to date"
        ));
        return Ok(());
    }
    for (path, text) in outputs {
        if stale.contains(&path.as_str()) {
            let full = ws.root.join(path);
            if let Some(dir) = full.parent() {
                fs::create_dir_all(dir)?;
            }
            fs::write(&full, text).with_context(|| format!("writing {path}"))?;
            println!("wrote {path}");
        }
    }
    if stale.is_empty() {
        println!("every file generated from {source} is up to date");
    }
    Ok(())
}

/// `cargo xtask gen codes --md`: the code tables as Markdown on stdout (for the docs site).
pub(crate) fn markdown(ws: &Workspace) -> Result<()> {
    print!("{}", render_markdown(&load(&ws.root)?));
    Ok(())
}

/// Every output as `(path relative to the root, contents)`.
fn render_all(root: &Path) -> Result<Vec<(String, String)>> {
    let codes = load(root)?;
    let mut pages = Vec::new();
    for e in &codes.entries {
        let path = format!("docs/errors/{}.md", e.code);
        let text = fs::read_to_string(root.join(&path)).with_context(|| format!("{}: no page {path}", e.code))?;
        pages.push((e.code.clone(), text));
    }
    let readme_path = root.join(ERRORS_README);
    let readme = fs::read_to_string(&readme_path).with_context(|| format!("reading {ERRORS_README}"))?;
    let schema = render_error_schema(&codes)?;
    let mut out = vec![
        (RUST.to_owned(), render_rust(&codes)),
        (RUST_EXPLAIN.to_owned(), render_rust_explain(&pages)),
        (TS.to_owned(), render_ts(&codes)),
        (TS_EXPLAIN.to_owned(), render_ts_explain(&pages)),
        (
            render::TS.to_owned(),
            render::render_ts(&codes, &read_text(root, render::RUST_ERRORS)?)?,
        ),
        (ERRORS_README.to_owned(), render_readme(&readme, &codes)?),
    ];
    out.extend(SCHEMAS.iter().map(|path| ((*path).to_owned(), schema.clone())));
    Ok(out)
}

fn read_text(root: &Path, path: &str) -> Result<String> {
    fs::read_to_string(root.join(path)).with_context(|| format!("reading {path}"))
}

/// Reads `codes.json`, validates it against its schema and checks what a schema can't say:
/// every group has a title, codes are unique, and the codes the TS layer raises are listed.
fn load(root: &Path) -> Result<Codes> {
    let read = |path: &str| -> Result<Value> {
        let text = fs::read_to_string(root.join(path)).with_context(|| format!("reading {path}"))?;
        serde_json::from_str(&text).with_context(|| format!("{path} is not JSON"))
    };
    let json = read(CODES)?;
    let schema = read(CODES_SCHEMA)?;
    validate(&schema, &json).with_context(|| format!("{CODES} does not match {CODES_SCHEMA}"))?;
    parse(&json, &schema)
}

/// Fails with every schema violation when `instance` does not match `schema` (2020-12).
pub(crate) fn validate(schema: &Value, instance: &Value) -> Result<()> {
    let id = schema
        .get("$id")
        .and_then(Value::as_str)
        .unwrap_or("urn:lamina:schema")
        .to_owned();
    let mut schemas = boon::Schemas::new();
    let mut compiler = boon::Compiler::new();
    compiler
        .add_resource(&id, schema.clone())
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    let index = compiler
        .compile(&id, &mut schemas)
        .map_err(|e| anyhow::anyhow!("the schema does not compile: {e}"))?;
    schemas.validate(instance, index).map_err(|e| anyhow::anyhow!("{e}"))
}

/// The validated JSON as [`Codes`].
fn parse(json: &Value, schema: &Value) -> Result<Codes> {
    let text = |v: &Value, key: &str| -> Result<String> {
        v.get(key)
            .and_then(Value::as_str)
            .map(str::to_owned)
            .with_context(|| format!("{CODES}: no string {key:?} in {v}"))
    };
    let strings = |v: Option<&Value>, what: &str| -> Result<Vec<String>> {
        v.and_then(Value::as_array)
            .with_context(|| format!("no list {what}"))?
            .iter()
            .map(|s| s.as_str().map(str::to_owned).context(what.to_owned()))
            .collect()
    };
    let groups = json.as_object().context("codes.json is not an object")?;
    for key in groups.keys() {
        if !NOT_CODE_GROUPS.contains(&key.as_str()) && !GROUPS.iter().any(|(g, _)| g == key) {
            bail!("{CODES}: group {key:?} has no title: add it to GROUPS in tools/xtask/src/codegen.rs");
        }
    }
    let mut entries = Vec::new();
    for (group, _) in GROUPS {
        for entry in groups.get(group).and_then(Value::as_array).into_iter().flatten() {
            entries.push(Entry {
                group: group.to_owned(),
                code: text(entry, "code")?,
                kind: text(entry, "kind")?,
                summary: text(entry, "summary")?,
                hint: text(entry, "hint")?,
            });
        }
    }
    let mut seen = std::collections::BTreeSet::new();
    if let Some(dup) = entries.iter().find(|e| !seen.insert(e.code.as_str())) {
        bail!("{CODES}: {} is listed twice (one namespace, ADR 0026 §3)", dup.code);
    }
    if let Some(missing) = ALSO_RAISED_BY_TS
        .iter()
        .find(|c| !entries.iter().any(|e| e.code == **c))
    {
        bail!("{CODES} does not list {missing:?}, which @laminapdf/sdk raises (ALSO_RAISED_BY_TS)");
    }
    Ok(Codes {
        docs_base: text(&json["docsUrl"], "base")?,
        docs_suffix: text(&json["docsUrl"], "suffix")?,
        kinds: strings(schema.pointer("/$defs/kind/enum"), "$defs.kind.enum of the schema")?,
        limits: strings(json.get("limits"), "limits")?,
        entries,
    })
}

/// `not-pdf` → `NotPdf`.
fn variant(code: &str) -> String {
    code.split('-')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect()
}

/// A Rust string literal.
fn rust_str(s: &str) -> String {
    format!("{s:?}")
}

/// A JSON string literal, which is also a valid TS one.
fn quoted(s: &str) -> String {
    Value::String(s.to_owned()).to_string()
}

/// The Rust module: one enum per type of code, each accessor a generated `match`.
fn render_rust(codes: &Codes) -> String {
    let mut out = format!(
        "{HEADER}\n\
         //! Every error and warning code the Rust crates and the WASM bindings raise, from\n\
         //! `fixtures/codes.json` (ADR 0026 §3): kind, summary, hint and `docsUrl` per code.\n\
         //! `cargo xtask check docs` fails when this file is stale.\n\
         #![allow(
    clippy::too_many_lines,
    clippy::match_same_arms,
    clippy::doc_markdown,
    reason = \"generated: one match arm per code; summaries are codes.json text\"
)]\n\n\
         use crate::ErrorKind;\n\n\
         /// The base of every `docsUrl` (ADR 0026 §6): `DOCS_URL_BASE` + code + `DOCS_URL_SUFFIX`.\n\
         pub const DOCS_URL_BASE: &str = {};\n\n\
         /// The suffix of every `docsUrl` (ADR 0026 §6).\n\
         pub const DOCS_URL_SUFFIX: &str = {};\n",
        rust_str(&codes.docs_base),
        rust_str(&codes.docs_suffix)
    );
    let rust: Vec<&Entry> = codes.entries.iter().filter(|e| !e.is_ts_only()).collect();
    let errors: Vec<&Entry> = rust.iter().copied().filter(|e| !e.is_warning()).collect();
    let warnings: Vec<&Entry> = rust.iter().copied().filter(|e| e.is_warning()).collect();
    rust_enum(
        &mut out,
        "ErrorCode",
        "Every error code lamina's Rust crates and its WASM binding raise (the codes only\n/// `@laminapdf/sdk` raises are not here), in `codes.json` order.",
        &errors,
    );
    rust_enum(
        &mut out,
        "WarningCode",
        "Every warning code, in `codes.json` order.",
        &warnings,
    );
    out
}

/// The façade's module of explain pages: each page's Markdown as a raw string literal.
fn render_rust_explain(pages: &[(String, String)]) -> String {
    let mut out = format!(
        "{HEADER}\n\
         //! The `explain` pages of every code in `fixtures/codes.json`, behind the `explain`\n\
         //! feature. `cargo xtask check docs` fails when this file is stale.\n\
         #![allow(clippy::too_many_lines, reason = \"generated: one match arm per code\")]\n"
    );
    out.push_str(
        "\n/// The `explain` page of `code`: the Markdown of `docs/errors/<code>.md`, for every code\n\
         /// in `codes.json` (including the ones only `@laminapdf/sdk` raises); `None` for an unknown\n\
         /// code. Behind the `explain` feature, so the text never reaches a build without it\n\
         /// (the WASM modules).\n\
         #[cfg(feature = \"explain\")]\n\
         #[must_use]\n\
         pub fn explain(code: &str) -> Option<&'static str> {\n    \
         Some(match code {\n",
    );
    for (code, text) in pages {
        let _ = writeln!(out, "        {} => {},", rust_str(code), raw_str(text));
    }
    out.push_str("        _ => return None,\n    })\n}\n");
    out
}

/// `text` as a Rust raw string literal: no `#` without a `"` in it, else one more `#` than the
/// longest `"#…` run.
fn raw_str(text: &str) -> String {
    let longest = text
        .match_indices('"')
        .map(|(index, _)| {
            text.get(index + 1..)
                .unwrap_or_default()
                .chars()
                .take_while(|c| *c == '#')
                .count()
        })
        .max()
        .unwrap_or(0);
    // No quote, no hashes (clippy's needless_raw_string_hashes); else one more than any run.
    let hashes = if text.contains('"') {
        "#".repeat(longest + 1)
    } else {
        String::new()
    };
    format!("r{hashes}\"{text}\"{hashes}")
}

/// One enum and its accessors.
fn rust_enum(out: &mut String, name: &str, doc: &str, entries: &[&Entry]) {
    let _ = write!(
        out,
        "\n/// {doc}\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n\
         #[non_exhaustive]\n\
         pub enum {name} {{\n"
    );
    for e in entries {
        let _ = writeln!(out, "    /// `{}`: {}.", e.code, e.summary);
        let _ = writeln!(out, "    {},", variant(&e.code));
    }
    let _ = write!(
        out,
        "}}\n\nimpl {name} {{\n    \
         /// Every variant, in `codes.json` order.\n    \
         pub const ALL: &'static [Self] = &[\n"
    );
    for e in entries {
        let _ = writeln!(out, "        Self::{},", variant(&e.code));
    }
    out.push_str(
        "    ];\n\n    \
         /// The code with this name, if there is one.\n    \
         #[must_use]\n    \
         pub const fn from_code(code: &str) -> Option<Self> {\n        \
         Some(match code.as_bytes() {\n",
    );
    for e in entries {
        let _ = writeln!(out, "            b{} => Self::{},", rust_str(&e.code), variant(&e.code));
    }
    out.push_str("            _ => return None,\n        })\n    }\n");
    let accessor = |out: &mut String, doc: &str, sig: &str, value: &dyn Fn(&Entry) -> String| {
        let _ = write!(
            out,
            "\n    /// {doc}\n    #[must_use]\n    pub const fn {sig} {{\n        match self {{\n"
        );
        for e in entries {
            let _ = writeln!(out, "            Self::{} => {},", variant(&e.code), value(e));
        }
        out.push_str("        }\n    }\n");
    };
    accessor(out, "The kebab-case code.", "as_str(self) -> &'static str", &|e| {
        rust_str(&e.code)
    });
    accessor(out, "The kind (ADR 0026 §2).", "kind(self) -> ErrorKind", &|e| {
        format!("ErrorKind::{}", variant(&e.kind))
    });
    accessor(
        out,
        "One lowercase sentence: what happened.",
        "summary(self) -> &'static str",
        &|e| rust_str(&e.summary),
    );
    accessor(
        out,
        "The hint (ADR 0026 §5), with its `{limit}`/`{option}` parameters unfilled.",
        "hint(self) -> &'static str",
        &|e| rust_str(&e.hint),
    );
    out.push_str(
        "\n    /// The code's explain page (`docsUrl`, ADR 0026 §6).\n    \
         #[must_use]\n    \
         pub fn docs_url(self) -> String {\n        \
         format!(\"{DOCS_URL_BASE}{}{DOCS_URL_SUFFIX}\", self.as_str())\n    \
         }\n}\n",
    );
}

/// `export type name = …;`, one member per line.
fn ts_union(out: &mut String, doc: &str, name: &str, members: &[&str]) {
    let _ = writeln!(out, "/** {doc} */");
    if members.is_empty() {
        let _ = writeln!(out, "export type {name} = never;\n");
        return;
    }
    let _ = writeln!(out, "export type {name} =");
    for (i, m) in members.iter().enumerate() {
        let end = if i + 1 == members.len() { ";" } else { "" };
        let _ = writeln!(out, "  | {}{end}", quoted(m));
    }
    out.push('\n');
}

/// `export const name: readonly ty[] = […];`, one member per line.
fn ts_list(out: &mut String, doc: &str, name: &str, ty: &str, members: &[&str]) {
    let _ = writeln!(out, "/** {doc} */");
    let _ = writeln!(out, "export const {name}: readonly {ty}[] = [");
    for m in members {
        let _ = writeln!(out, "  {},", quoted(m));
    }
    out.push_str("];\n\n");
}

/// `export const name: { readonly [C in ty]: value } = { code: …, };`.
fn ts_record(out: &mut String, doc: &str, name: &str, value_ty: &str, rows: &[(&str, String)]) {
    let _ = writeln!(out, "/** {doc} */");
    let _ = writeln!(
        out,
        "export const {name}: {{ readonly [C in ErrorCode | WarningCode]: {value_ty} }} = {{"
    );
    for (code, value) in rows {
        let _ = writeln!(out, "  {}: {value},", quoted(code));
    }
    out.push_str("};\n\n");
}

/// The TS module of codes, kinds and hints.
fn render_ts(codes: &Codes) -> String {
    let errors: Vec<&str> = codes
        .entries
        .iter()
        .filter(|e| !e.is_warning())
        .map(|e| e.code.as_str())
        .collect();
    let warnings: Vec<&str> = codes
        .entries
        .iter()
        .filter(|e| e.is_warning())
        .map(|e| e.code.as_str())
        .collect();
    let kinds: Vec<&str> = codes.kinds.iter().map(String::as_str).collect();
    let limits: Vec<&str> = codes.limits.iter().map(String::as_str).collect();
    let mut out = format!(
        "{HEADER}\n// From fixtures/codes.json (ADR 0026 §3); `cargo xtask check docs` fails when it is stale.\n\n"
    );
    ts_union(
        &mut out,
        "The nine kinds of ADR 0026 §2: what the caller can do about an error.",
        "ErrorKind",
        &kinds,
    );
    ts_union(
        &mut out,
        "Every error code (ADR 0026 §3; `fixtures/codes.json`).",
        "ErrorCode",
        &errors,
    );
    ts_union(
        &mut out,
        "Every warning code (ADR 0026 §3; `fixtures/codes.json`).",
        "WarningCode",
        &warnings,
    );
    ts_union(
        &mut out,
        "The names of the `Limits` (ADR 0003 §3), as `data.limit` of `limit-exceeded`.",
        "LimitName",
        &limits,
    );
    ts_list(
        &mut out,
        "Every error code, in `codes.json` order.",
        "ERROR_CODES",
        "ErrorCode",
        &errors,
    );
    ts_list(
        &mut out,
        "Every warning code, in `codes.json` order.",
        "WARNING_CODES",
        "WarningCode",
        &warnings,
    );
    let rows = |f: &dyn Fn(&Entry) -> String| -> Vec<(&str, String)> {
        codes.entries.iter().map(|e| (e.code.as_str(), f(e))).collect()
    };
    ts_record(
        &mut out,
        "The kind of every code.",
        "KINDS",
        "ErrorKind",
        &rows(&|e| quoted(&e.kind)),
    );
    ts_record(
        &mut out,
        "The hint of every code (ADR 0026 §5), with its `{limit}`/`{option}` parameters unfilled.",
        "HINTS",
        "string",
        &rows(&|e| quoted(&e.hint)),
    );
    let _ = writeln!(
        out,
        "/** `docsUrl` = base + code + suffix (ADR 0026 §6). */\n\
         export const DOCS_URL = {{ base: {}, suffix: {} }} as const;\n\n\
         /** The explain page of `code` (`docsUrl`, ADR 0026 §6). */\n\
         export function docsUrl(code: ErrorCode | WarningCode): string {{\n  \
         return `${{DOCS_URL.base}}${{code}}${{DOCS_URL.suffix}}`;\n\
         }}\n",
        quoted(&codes.docs_base),
        quoted(&codes.docs_suffix)
    );
    ts_groups(&mut out);
    ts_raised_by_package(&mut out, codes);
    out
}

/// The groups of `codes.json`, by what they list (for the tests that read the file).
fn ts_groups(out: &mut String) {
    let names = |warnings: bool| -> Vec<&str> {
        GROUPS
            .iter()
            .map(|(g, _)| *g)
            .filter(|g| is_warning_group(g) == warnings)
            .collect()
    };
    ts_list(
        out,
        "The groups of `codes.json` that list errors.",
        "ERROR_GROUPS",
        "string",
        &names(false),
    );
    ts_list(
        out,
        "The groups of `codes.json` that list warnings.",
        "WARNING_GROUPS",
        "string",
        &names(true),
    );
    ts_list(
        out,
        "The groups whose codes only `@laminapdf/sdk` raises (not in the Rust enums or the WASM).",
        "TS_ONLY_GROUPS",
        "string",
        &TS_ONLY_GROUPS,
    );
}

/// `RAISED_BY_PACKAGE`: kind and hint of the codes the TS layer raises itself.
fn ts_raised_by_package(out: &mut String, codes: &Codes) {
    out.push_str(
        "/** Kind and hint of the codes `@laminapdf/sdk` raises itself (the WASM fills in the others). */\n\
         export const RAISED_BY_PACKAGE = {\n",
    );
    for e in codes
        .entries
        .iter()
        .filter(|e| e.is_ts_only() || ALSO_RAISED_BY_TS.contains(&e.code.as_str()))
    {
        let _ = writeln!(
            out,
            "  {}: {{ kind: {}, hint: {} }},",
            quoted(&e.code),
            quoted(&e.kind),
            quoted(&e.hint)
        );
    }
    out.push_str("} as const;\n");
}

/// The TS module of explain pages.
fn render_ts_explain(pages: &[(String, String)]) -> String {
    let mut out = format!(
        "{HEADER}\n// From docs/errors/<code>.md; `cargo xtask check docs` fails when it is stale. Imported only\n\
         // by the `@laminapdf/sdk/explain` subpath, so the text stays out of the main bundle.\n\n\
         import type {{ ErrorCode, WarningCode }} from \"./codes.js\";\n\n\
         /** Every code's explain page (ADR 0026 §6), as Markdown. */\n\
         export const PAGES: {{ readonly [C in ErrorCode | WarningCode]: string }} = {{\n"
    );
    for (code, text) in pages {
        let _ = writeln!(out, "  {}: {},", quoted(code), quoted(text));
    }
    out.push_str("};\n");
    out
}

/// The JSON Schema `laminapdf.error/1` of the ADR 0026 §1 object.
fn render_error_schema(codes: &Codes) -> Result<String> {
    let codes_of = |warning: bool| -> Vec<&str> {
        codes
            .entries
            .iter()
            .filter(|e| e.is_warning() == warning)
            .map(|e| e.code.as_str())
            .collect()
    };
    let docs_url = json!({
        "description": "The code's explain page: base + code + suffix (ADR 0026 §6).",
        "type": "string",
        "pattern": format!("^{}[a-z0-9-]+{}$", regex_escape(&codes.docs_base), regex_escape(&codes.docs_suffix)),
    });
    let common = |code_enum: Vec<&str>, with_did_you_mean: bool| {
        let mut properties = json!({
            "code": { "description": "The stable kebab-case code (fixtures/codes.json).", "enum": code_enum },
            "kind": { "$ref": "#/$defs/kind" },
            "message": {
                "description": "One lowercase sentence. Never document text (ADR 0026 §4).",
                "type": "string",
                "minLength": 1
            },
            "hint": {
                "description": "One actionable sentence for this code. Never document text.",
                "type": "string",
                "minLength": 1
            },
            "location": { "$ref": "#/$defs/location" },
            "data": {
                "description": "Code-specific fields, listed on the code's page; the only place document-derived strings appear (untrusted).",
                "type": "object"
            },
            "docsUrl": docs_url.clone(),
        });
        // Warnings have the same shape without `didYouMean` (ADR 0026 §1): `false` forbids it.
        let did_you_mean = if with_did_you_mean {
            json!({
                "description": "For usage errors: the closest names from lamina's own vocabulary.",
                "type": "array",
                "items": { "type": "string" },
                "minItems": 1
            })
        } else {
            json!(false)
        };
        if let Some(map) = properties.as_object_mut() {
            map.insert("didYouMean".to_owned(), did_you_mean);
        }
        json!({
            "type": "object",
            "required": ["code", "kind", "message", "docsUrl"],
            "properties": properties,
        })
    };
    let schema = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/laudebugs/laminapdf/blob/main/packages/sdk/schemas/error.schema.json",
        "title": "laminapdf.error/1",
        "description": "An error or warning of every lamina surface (ADR 0026 §1): camelCase keys, optional keys omitted (never null). Generated from fixtures/codes.json by `cargo xtask gen codes`; do not edit. New optional keys may appear within version 1; consumers ignore unknown keys.",
        "oneOf": [{ "$ref": "#/$defs/error" }, { "$ref": "#/$defs/warning" }],
        "$defs": {
            "error": common(codes_of(false), true),
            "warning": common(codes_of(true), false),
            "kind": {
                "description": "The nine kinds of ADR 0026 §2.",
                "enum": codes.kinds,
            },
            "location": {
                "description": "Where the problem is (ADR 0026 §1.1); every value is lamina-made.",
                "type": "object",
                "additionalProperties": false,
                "properties": {
                    "offset": { "description": "Byte offset in the input file.", "type": "integer", "minimum": 0 },
                    "object": { "description": "Object number of the indirect object the problem is in or at.", "type": "integer", "minimum": 0 },
                    "streamOffset": { "description": "Byte offset in the decoded data of `object`.", "type": "integer", "minimum": 0 },
                    "pageIndex": { "description": "0-based page index (ADR 0027 §6).", "type": "integer", "minimum": 0 },
                    "id": { "description": "A LaminaPdfId (p12.0).", "type": "string" }
                },
                "dependentRequired": { "streamOffset": ["object"] }
            }
        }
    });
    Ok(serde_json::to_string_pretty(&schema)? + "\n")
}

/// `s` with the regex metacharacters escaped.
fn regex_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if "\\.+*?()|[]{}^$/".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// The code tables: one per group, in [`GROUPS`] order.
fn render_markdown(codes: &Codes) -> String {
    let mut out = String::new();
    for (group, title) in GROUPS {
        let rows: Vec<&Entry> = codes.entries.iter().filter(|e| e.group == group).collect();
        if rows.is_empty() {
            continue;
        }
        let _ = write!(out, "\n## {title}\n\n| Code | Kind | Summary |\n| --- | --- | --- |\n");
        for e in rows {
            let _ = writeln!(
                out,
                "| [`{code}`]({code}.md) | `{}` | {} |",
                e.kind,
                e.summary.replace('|', "\\|"),
                code = e.code
            );
        }
    }
    out
}

/// `docs/errors/README.md`: its hand-written part up to the marker, then the tables.
fn render_readme(current: &str, codes: &Codes) -> Result<String> {
    let Some((intro, _)) = current.split_once(README_MARKER) else {
        bail!("{ERRORS_README} has no line {README_MARKER:?}");
    };
    Ok(format!("{intro}{README_MARKER}\n{}", render_markdown(codes)))
}

