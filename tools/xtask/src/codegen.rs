//! `cargo xtask gen codes [--check | --md]`: the error contract of ADR 0026, generated from
//! `fixtures/codes.json` for every surface (L1b; code organisation §9).
//!
//! It validates `codes.json` against `fixtures/codes.schema.json`, then writes:
//!
//! - `crates/laminapdf-syntax/src/generated/codes.rs`: the `ErrorCode` and `WarningCode` enums
//!   (`as_str`, `from_code`, `kind`, `summary`, `hint`, `docs_url`), in the bottom crate so every
//!   crate that builds an ADR 0026 object reads the same table (the façade re-exports them);
//! - `crates/laminapdf/src/generated/explain.rs`: behind the façade's `explain` feature,
//!   `explain(code)` with the text of the `docs/errors/<code>.md` pages as raw strings, so the
//!   published crate needs no file outside it, and no build without the feature carries them;
//! - `packages/sdk/src/generated/codes.ts`: the `ErrorKind`, `ErrorCode`, `WarningCode` and
//!   `LimitName` unions, the code lists, `KINDS`, `HINTS`, `docsUrl()` and the kind and hint of
//!   the codes the TS layer raises itself;
//! - `packages/sdk/src/generated/explain.ts`: every page's text, for the `@laminapdf/sdk/explain`
//!   subpath only;
//! - `packages/render/src/generated/codes.ts`: the render backends' codes, kinds and docs URL
//!   ([`render`]);
//! - the JSON Schema `laminapdf.error/1` of the ADR 0026 §1 object, in `packages/sdk/schemas/` and
//!   `crates/laminapdf/schemas/`;
//! - the code tables of `docs/errors/README.md` (below its marker line), which `--md` prints.
//!
//! `--check` renders everything in memory and fails, naming each file, when any differs from
//! what is committed. It needs no build and no `node_modules`, so `cargo xtask check docs` runs
//! it. The TS files are excluded from Biome (`biome.json`), like other generated code.

