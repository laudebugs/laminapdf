fn icon(status: Option<Status>) -> &'static str {
    match status {
        None => "—",
        Some(Status::Unsupported) => "🔴 unsupported",
        Some(Status::Read) => "🟡 read",
        Some(Status::Write) => "🔵 write",
        Some(Status::RoundTrip) => "🟢 round-trip",
    }
}

/// The README for this manifest and evidence.
pub(crate) fn render(manifest: &Manifest, matrix: &Matrix<'_>) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n## Summary\n\nRows per surface by best proven status (of the rows that target the surface).\n\n");
    out.push_str("| Surface | Rows | 🟢 round-trip | 🔵 write | 🟡 read | 🔴 unsupported | — none | At target |\n");
    out.push_str("| --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for surface in Surface::ALL {
        let rows: Vec<&Row> = manifest.rows.iter().filter(|r| r.surfaces.contains(&surface)).collect();
        let count = |status: Option<Status>| rows.iter().filter(|r| matrix.status(&r.id, surface) == status).count();
        let at_target = rows
            .iter()
            .filter(|r| matrix.status(&r.id, surface).is_some_and(|s| s >= r.target))
            .count();
        let _ = writeln!(
            out,
            "| {surface} | {} | {} | {} | {} | {} | {} | {at_target} |",
            rows.len(),
            count(Some(Status::RoundTrip)),
            count(Some(Status::Write)),
            count(Some(Status::Read)),
            count(Some(Status::Unsupported)),
            count(None),
        );
    }
    for group in &manifest.groups {
        let _ = write!(out, "\n## {}. {}\n\n", group.letter, group.name);
        out.push_str("| ID | Operation | core | pdf | web | desktop | Target | Evidence |\n");
        out.push_str("| --- | --- | --- | --- | --- | --- | --- | --- |\n");
        for row in manifest.rows.iter().filter(|r| r.group() == group.letter) {
            let cells: Vec<&str> = Surface::ALL
                .iter()
                .map(|s| {
                    if row.surfaces.contains(s) {
                        icon(matrix.status(&row.id, *s))
                    } else {
                        "n/a"
                    }
                })
                .collect();
            let _ = writeln!(
                out,
                "| {} | {} | {} | {} {} | {} |",
                row.id,
                md_cell(&row.name),
                cells.join(" | "),
                row.round,
                row.target,
                evidence(matrix, &row.id)
            );
        }
    }
    out
}

/// `[fn](path) core read` for each tag of the row (a TypeScript test by its title), joined
/// with `<br>`.
fn evidence(matrix: &Matrix<'_>, id: &str) -> String {
    let Some(tags) = matrix.evidence.get(id) else {
        return String::new();
    };
    tags.iter()
        .map(|(test, surface, status)| {
            let name = match test.runner {
                Runner::Cargo { .. } => format!("`{}`", test.function),
                Runner::Suite(_) => md_cell(&test.function).replace('[', "\\[").replace(']', "\\]"),
            };
            format!("[{name}](../../{}) {surface} {status}", test.file)
        })
        .collect::<Vec<_>>()
        .join("<br>")
}

/// `docs/capabilities/matrix.json`: the same matrix as data, for the web reader's capability
/// page, which bundles it when it is built.
#[derive(Serialize)]
struct JsonMatrix<'a> {
    version: u32,
    groups: Vec<JsonGroup<'a>>,
}

#[derive(Serialize)]
struct JsonGroup<'a> {
    id: String,
    name: &'a str,
    ops: Vec<JsonOp<'a>>,
}

#[derive(Serialize)]
struct JsonOp<'a> {
    id: &'a str,
    name: &'a str,
    round: &'a str,
    target: &'static str,
    /// Per surface: the best proven status, `null` for no evidence, `"n/a"` when the row
    /// doesn't target it.
    surfaces: JsonSurfaces,
}

#[derive(Serialize)]
struct JsonSurfaces {
    core: Option<&'static str>,
    pdf: Option<&'static str>,
    web: Option<&'static str>,
    desktop: Option<&'static str>,
}

/// The matrix as `matrix.json` (version 1): groups in the manifest's order, each with its
/// rows; pretty-printed with a trailing newline.
pub(crate) fn render_json(manifest: &Manifest, matrix: &Matrix<'_>) -> anyhow::Result<String> {
    let cell = |row: &Row, surface: Surface| {
        if row.surfaces.contains(&surface) {
            matrix.status(&row.id, surface).map(Status::name)
        } else {
            Some("n/a")
        }
    };
    let groups = manifest
        .groups
        .iter()
        .map(|group| JsonGroup {
            id: group.letter.to_string(),
            name: &group.name,
            ops: manifest
                .rows
                .iter()
                .filter(|r| r.group() == group.letter)
                .map(|row| JsonOp {
                    id: &row.id,
                    name: &row.name,
                    round: &row.round,
                    target: row.target.name(),
                    surfaces: JsonSurfaces {
                        core: cell(row, Surface::Core),
                        pdf: cell(row, Surface::Pdf),
                        web: cell(row, Surface::Web),
                        desktop: cell(row, Surface::Desktop),
                    },
                })
                .collect(),
        })
        .collect();
    let mut json = serde_json::to_string_pretty(&JsonMatrix { version: 1, groups })?;
    json.push('\n');
    Ok(json)
}

/// The statuses a README claims: `(ID, surface) → status` for every non-empty cell, and the
/// IDs of its rows in order (to check each manifest row appears once).
pub(crate) fn claims(readme: &str) -> (BTreeMap<(String, Surface), Status>, Vec<String>) {
    let mut claimed = BTreeMap::new();
    let mut ids = Vec::new();
    for line in readme.lines() {
        let Some(row) = line.strip_prefix('|') else { continue };
        let cells = split_cells(row);
        let Some(id) = cells.first().filter(|id| super::manifest::is_id(id)) else {
            continue;
        };
        ids.push(id.clone());
        for (surface, cell) in Surface::ALL.into_iter().zip(cells.iter().skip(2)) {
            if let Some(status) = cell.split_whitespace().find_map(Status::parse) {
                claimed.insert((id.clone(), surface), status);
            }
        }
    }
    (claimed, ids)
}

/// Claims in `readme` that no tag could prove (`upper` treats every tag as passing), and rows
/// missing, repeated or unknown. Needs no test run, so `check docs` runs it on every PR.
pub(crate) fn overclaims(manifest: &Manifest, readme: &str, upper: &Matrix<'_>) -> Vec<String> {
    let (claimed, ids) = claims(readme);
    let mut problems = Vec::new();
    for ((id, surface), status) in &claimed {
        match upper.status(id, *surface) {
            Some(best) if best >= *status => {}
            best => problems.push(format!(
                "{id} {surface}: the README claims `{status}`, but {}",
                best.map_or("no test is tagged for it".to_owned(), |s| format!(
                    "the tagged tests prove at most `{s}`"
                ))
            )),
        }
    }
    for row in &manifest.rows {
        match ids.iter().filter(|id| **id == row.id).count() {
            1 => {}
            n => problems.push(format!("{}: the README has {n} rows for it, not 1", row.id)),
        }
    }
    for id in &ids {
        if manifest.row(id).is_none() {
            problems.push(format!("{id}: in the README but not in the manifest"));
        }
    }
    problems
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;
    use std::path::Path;

    use super::*;
    use crate::capabilities::tags::scan_rust;

    const MANIFEST: &str = r#"
version = 1

[[group]]
id = "C"
name = "Pages"

[[op]]
id = "C.01"
name = "Rotate | flip"
round = "E2"

[[op]]
id = "C.02"
name = "Crop"
round = "E2"
target = "read"
surfaces = ["core", "pdf"]
"#;

    const SOURCE: &str = "
/// capability: C.01 core read
#[test]
fn reads() {}

/// capability: C.01 core round-trip
#[test]
fn round_trips() {}
";

    fn fixture() -> (Manifest, Vec<Tag>) {
        let manifest = Manifest::parse(MANIFEST).unwrap();
        let tags = scan_rust(Path::new("crates/lamina-x/tests/t.rs"), SOURCE, &BTreeSet::new()).unwrap();
        (manifest, tags)
    }

    #[test]
    fn render_json_should_give_each_surface_its_status_null_or_n_a() {
        let (manifest, tags) = fixture();
        let json: serde_json::Value =
            serde_json::from_str(&render_json(&manifest, &Matrix::from_tags(&tags)).unwrap()).unwrap();
        assert_eq!(
            json,
            serde_json::json!({
                "version": 1,
                "groups": [{
                    "id": "C",
                    "name": "Pages",
                    "ops": [
                        { "id": "C.01", "name": "Rotate | flip", "round": "E2", "target": "round-trip",
                          "surfaces": { "core": "round-trip", "pdf": null, "web": null, "desktop": null } },
                        { "id": "C.02", "name": "Crop", "round": "E2", "target": "read",
                          "surfaces": { "core": null, "pdf": null, "web": "n/a", "desktop": "n/a" } }
                    ]
                }]
            })
        );
    }

    #[test]
    fn render_json_should_end_with_a_newline_and_keep_the_fields_in_order() {
        let (manifest, tags) = fixture();
        let json = render_json(&manifest, &Matrix::from_tags(&tags)).unwrap();
        assert!(json.ends_with("}\n"));
        assert!(json.find("\"version\"") < json.find("\"groups\""));
    }

    #[test]
    fn render_should_name_a_typescript_test_by_its_title() {
        let manifest = Manifest::parse(&MANIFEST.replace("surfaces = [\"core\", \"pdf\"]", "")).unwrap();
        let tags = crate::capabilities::tags::scan_ts(
            Path::new("apps/web/e2e/pages.e2e.test.ts"),
            "it(\"[cap C.02 web read] shows the [crop] box\", () => {});",
        )
        .unwrap();
        let readme = render(&manifest, &Matrix::from_tags(&tags));
        assert!(readme.contains("[shows the \\[crop\\] box](../../apps/web/e2e/pages.e2e.test.ts) web read"));
    }

    #[test]
    fn from_tags_should_keep_the_best_status() {
        let (_, tags) = fixture();
        let matrix = Matrix::from_tags(&tags);
        assert_eq!(matrix.status("C.01", Surface::Core), Some(Status::RoundTrip));
    }

    #[test]
    fn render_should_mark_untargeted_surfaces_na_and_escape_names() {
        let (manifest, tags) = fixture();
        let readme = render(&manifest, &Matrix::from_tags(&tags));
        assert!(
            readme.contains("| C.02 | Crop | — | — | n/a | n/a | E2 read |  |"),
            "{readme}"
        );
        assert!(readme.contains("| C.01 | Rotate \\| flip | 🟢 round-trip | — | — | — | E2 round-trip |"));
    }

    #[test]
    fn render_should_link_each_test() {
        let (manifest, tags) = fixture();
        let readme = render(&manifest, &Matrix::from_tags(&tags));
        assert!(readme.contains("[`reads`](../../crates/lamina-x/tests/t.rs) core read<br>"));
    }

    #[test]
    fn render_should_count_rows_at_target_in_the_summary() {
        let (manifest, tags) = fixture();
        let readme = render(&manifest, &Matrix::from_tags(&tags));
        assert!(readme.contains("| core | 2 | 1 | 0 | 0 | 0 | 1 | 1 |"), "{readme}");
    }

    #[test]
    fn claims_should_read_back_what_render_wrote() {
        let (manifest, tags) = fixture();
        let readme = render(&manifest, &Matrix::from_tags(&tags));
        let (claimed, ids) = claims(&readme);
        assert_eq!(
            (claimed.into_iter().collect::<Vec<_>>(), ids),
            (
                vec![(("C.01".to_owned(), Surface::Core), Status::RoundTrip)],
                vec!["C.01".to_owned(), "C.02".to_owned()]
            )
        );
    }

    #[test]
    fn overclaims_should_accept_a_generated_readme() {
        let (manifest, tags) = fixture();
        let upper = Matrix::from_tags(&tags);
        assert_eq!(
            overclaims(&manifest, &render(&manifest, &upper), &upper),
            Vec::<String>::new()
        );
    }

    #[test]
    fn overclaims_should_reject_a_status_no_tag_proves() {
        let (manifest, tags) = fixture();
        let upper = Matrix::from_tags(&tags);
        let readme = render(&manifest, &upper).replace("| C.02 | Crop | —", "| C.02 | Crop | 🟡 read");
        assert_eq!(overclaims(&manifest, &readme, &upper).len(), 1);
    }

    #[test]
    fn overclaims_should_reject_a_missing_row() {
        let (manifest, tags) = fixture();
        let upper = Matrix::from_tags(&tags);
        let readme = render(&manifest, &upper)
            .lines()
            .filter(|l| !l.starts_with("| C.02"))
            .collect::<Vec<_>>()
            .join("\n");
        assert_eq!(overclaims(&manifest, &readme, &upper).len(), 1);
    }

    #[test]
    fn tag_problems_should_reject_an_untargeted_surface_and_an_unknown_id() {
        let (manifest, _) = fixture();
        let source =
            "/// capability: C.02 web read\n#[test]\nfn a() {}\n/// capability: C.09 core read\n#[test]\nfn b() {}\n";
        let tags = scan_rust(Path::new("crates/x/tests/t.rs"), source, &BTreeSet::new()).unwrap();
        assert_eq!(tag_problems(&manifest, &tags).len(), 2);
    }

    #[test]
    fn tag_problems_should_reject_core_round_trip_outside_the_round_trip_suite() {
        let (manifest, tags) = fixture();
        assert_eq!(tag_problems(&manifest, &tags).len(), 1);
    }

    #[test]
    fn tag_problems_should_accept_core_round_trip_in_the_round_trip_suite() {
        let (manifest, _) = fixture();
        let tags = scan_rust(Path::new(ROUND_TRIP_SUITE), SOURCE, &BTreeSet::new()).unwrap();
        assert_eq!(tag_problems(&manifest, &tags), Vec::<String>::new());
    }
}
