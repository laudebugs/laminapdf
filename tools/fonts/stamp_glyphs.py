#!/usr/bin/env python3
"""Writes the lettering of the standard stamp annotations (todo E5c) as outlines in Rust:
crates/laminapdf-build/src/annot/appearance/stamp/glyphs.rs.

A standard stamp's appearance draws its name as filled paths, so it needs no font: it works in the
WebAssembly base module and leaves a PDF/A file's fonts as they were. The outlines are Lamina Sans
Bold (Source Sans 3 renamed, SIL OFL 1.1; see packages/fonts/README.md), read from the committed
@laminapdf/fonts file at weight 700, so the script needs no download.

    python3 -m venv .venv && .venv/bin/pip install -r tools/fonts/requirements.txt
    .venv/bin/python tools/fonts/stamp_glyphs.py            # rewrite glyphs.rs
    .venv/bin/python tools/fonts/stamp_glyphs.py --check    # fail unless it is up to date

Quadratic TrueType curves become cubic ones (PDF has no quadratic curve), with every coordinate
rounded to a whole font unit (1/1000 em). Run it by hand when the font or the characters change.
"""

import argparse
import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "packages" / "fonts" / "files" / "lamina-sans-latin-wght-normal.woff2"
OUTPUT = ROOT / "crates" / "laminapdf-build" / "src" / "annot" / "appearance" / "stamp" / "glyphs.rs"
WEIGHT = 700
# What stamp names are written in: capitals, the space, and what a name could add later.
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ -"


class Segments(BasePen):
    """Records a glyph as M, L, C and Z segments; BasePen turns each quadratic curve into a cubic."""

    def __init__(self, glyphs):
        super().__init__(glyphs)
        self.out = []

    def _moveTo(self, p):
        self.out.append(("M", p))

    def _lineTo(self, p):
        self.out.append(("L", p))

    def _curveToOne(self, p1, p2, p3):
        self.out.append(("C", p1, p2, p3))

    def _closePath(self):
        self.out.append(("Z",))

    def _endPath(self):
        self.out.append(("Z",))


def point(p):
    return f"{round(p[0])}, {round(p[1])}"


def render():
    font = TTFont(SOURCE)
    bold = instancer.instantiateVariableFont(font, {"wght": WEIGHT})
    cmap = bold.getBestCmap()
    glyphs = bold.getGlyphSet()
    hmtx = bold["hmtx"]
    upem = bold["head"].unitsPerEm
    lines = [
        "//! Generated by `tools/fonts/stamp_glyphs.py` from Lamina Sans Bold (Source Sans 3, SIL OFL 1.1:",
        "//! `packages/fonts/LICENSES/`). Do not edit by hand.",
        "",
        "use super::font::{Glyph, Seg};",
        "",
        "/// Font units per em.",
        f"pub(super) const UNITS_PER_EM: f64 = {upem}.0;",
        "",
        "/// Cap height, in font units.",
        f"pub(super) const CAP_HEIGHT: f64 = {bold['OS/2'].sCapHeight}.0;",
        "",
        "/// The glyphs, by character.",
        "#[rustfmt::skip]",
        "pub(super) const GLYPHS: &[(char, Glyph)] = &[",
    ]
    for ch in CHARS:
        name = cmap[ord(ch)]
        pen = Segments(glyphs)
        glyphs[name].draw(pen)
        advance = hmtx[name][0]
        lines.append(f"    ({ch!r}, Glyph {{ advance: {advance}, path: &[")
        for seg in pen.out:
            if seg[0] == "M":
                lines.append(f"        Seg::M({point(seg[1])}),")
            elif seg[0] == "L":
                lines.append(f"        Seg::L({point(seg[1])}),")
            elif seg[0] == "C":
                lines.append(f"        Seg::C({point(seg[1])}, {point(seg[2])}, {point(seg[3])}),")
            else:
                lines.append("        Seg::Z,")
        lines.append("    ] }),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail unless glyphs.rs is up to date")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT.relative_to(ROOT)} is stale: run tools/fonts/stamp_glyphs.py")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
