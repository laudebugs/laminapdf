// The icon set as data: each file linted and reduced to its inner markup, the aliases checked, and
// the generated module written from them. The generator, the lint script and the tests share it.

import { lintIcon } from "./rules.ts";

/** Every icon's inner markup by name, aliases included, sorted by name. */
export type IconSet = Map<string, string>;

const INNER = /^<svg [^>]*>(.*)<\/svg>$/s;
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** Lints every file (throwing with every error found) and adds each alias under its own name. */
export function readIcons(files: [string, string][], aliases: Record<string, string>): IconSet {
  const errors = files.flatMap(([name, text]) => [
    ...lintIcon(name, text).errors,
    ...(NAME.test(name) ? [] : [`${name}: file names are lowercase words joined by hyphens`]),
  ]);
  if (errors.length > 0) throw new Error(`icons that break the rules:\n${errors.join("\n")}`);
  const icons: IconSet = new Map(files.map(([name, text]) => [name, INNER.exec(text.trim())?.[1] ?? ""]));
  for (const [alias, target] of Object.entries(aliases)) {
    const markup = icons.get(target);
    if (markup === undefined) throw new Error(`alias ${alias} names ${target}, which isn't an icon`);
    if (icons.has(alias)) throw new Error(`alias ${alias} is also an icon file`);
    icons.set(alias, markup);
  }
  return new Map([...icons].sort(([a], [b]) => (a < b ? -1 : 1)));
}

/** src/generated/icons.ts: the markup record and the name union. */
export function emitIcons(icons: IconSet): string {
  const entries = [...icons].map(([name, markup]) => `  ${JSON.stringify(name)}: ${JSON.stringify(markup)},`);
  return [
    "// @generated by packages/icons/scripts/generate.ts from svg/*.svg and aliases.json: do not edit.",
    "",
    "/** Every icon's inner SVG markup (the shapes inside the 24-unit `<svg>`), by name. */",
    "export const ICONS = {",
    ...entries,
    "} as const;",
    "",
    "/** An icon's name: its file name in `svg/` without `.svg`, or an alias from `aliases.json`. */",
    "export type IconName = keyof typeof ICONS;",
    "",
  ].join("\n");
}
