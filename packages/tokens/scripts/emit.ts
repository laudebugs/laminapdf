// The generator's three outputs from the flattened tokens: the CSS custom properties, the
// TypeScript constants and the contrast table. Pure functions of `tokens`, so `--check` compares
// strings.

import {
  ACCENTS,
  APPEARANCES,
  aliasOf,
  type Colour,
  contexts,
  DEFAULT_ACCENT,
  type Dimension,
  fixedContext,
  type Measured,
  measure,
  resolve,
  resolveFor,
  swapAccent,
  THEMES,
  type Token,
} from "./model.ts";

const HEADER = "@generated by packages/tokens/scripts/generate.ts from tokens.json: do not edit";

// ---- CSS names -----------------------------------------------------------------------------

/** Top-level groups emitted once, at `:root`, whatever the theme or appearance. */
const FIXED = ["semantic", "font", "type", "breakpoint", "motion", "component", "annotation", "content"];
/** The groups whose names keep their group as a prefix (`--paper-font-sans`). */
const PREFIXED = new Set(["font", "type", "annotation", "content"]);

/** The custom property name of a token, without `--paper-`; undefined for primitives. */
export function cssName(path: string): string | undefined {
  const [group, a, b, ...rest] = path.split(".");
  switch (group) {
    case "theme":
      return [b, ...rest].join("-");
    case "accent":
      return b === "page" ? ["page", ...rest].join("-") : rest.join("-");
    case "appearance":
      return ["page", b, ...rest].join("-");
    case "primitive":
      return undefined;
    default:
      if (group === undefined || !FIXED.includes(group)) throw new Error(`${path}: no CSS name rule for its group`);
      return [...(PREFIXED.has(group) ? [group] : []), a, b, ...rest].filter((s) => s !== undefined).join("-");
  }
}

/** The part of a path that decides where its custom property is declared. */
function scope(path: string): string {
  const parts = path.split(".");
  const depth = { theme: 2, accent: 3, appearance: 2 }[parts[0] ?? ""] ?? 1;
  return parts.slice(0, depth).join(".");
}

// ---- values --------------------------------------------------------------------------------

const GENERIC = new Set(["serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-monospace"]);

function length(d: Dimension): string {
  return d.value === 0 ? "0" : `${d.value}${d.unit}`;
}

function colour(c: Colour): string {
  const [r, g, b] = c.components.map((x) => Math.round(x * 255));
  if (c.alpha === undefined || c.alpha === 1) return c.hex ?? `rgb(${r}, ${g}, ${b})`;
  return `rgba(${r}, ${g}, ${b}, ${c.alpha})`;
}

function shadow(token: Token): string {
  type Layer = { color: Colour; offsetX: Dimension; offsetY: Dimension; blur: Dimension; spread: Dimension };
  const layers = token.value as Layer[];
  if (layers.every((l) => l.color.alpha === 0)) return "none";
  return layers
    .map((l) => `${[l.offsetX, l.offsetY, l.blur, l.spread].map(length).join(" ")} ${colour(l.color)}`)
    .join(", ");
}

/** A font stack as CSS: generic families bare, every other name quoted. */
function fontStack(value: unknown): string {
  return (value as string[]).map((f) => (GENERIC.has(f) ? f : `"${f}"`)).join(", ");
}

interface Typography {
  fontFamily: string;
  fontSize: string;
  fontWeight: number;
  lineHeight: number;
  letterSpacing: Dimension;
}

/** A resolved token's value as CSS, for the types tokens.json uses. */
function literal(token: Token): string {
  switch (token.type) {
    case "color":
      return token.lamina.system ?? colour(token.value as Colour);
    case "dimension":
      return length(token.value as Dimension);
    case "duration":
      return `${(token.value as Dimension).value}ms`;
    case "number":
      return String(token.value);
    case "fontFamily":
      return fontStack(token.value);
    case "shadow":
      return shadow(token);
    default:
      throw new Error(`${token.path}: no CSS for $type ${token.type}`);
  }
}

/**
 * A token's CSS value: an alias stays a `var()` when its target is declared wherever the token is
 * (same theme or accent block, or a fixed `:root` group), so overriding one moves the other;
 * any other alias is written out, since its target may hold another theme's value there.
 */
function cssValue(tokens: Map<string, Token>, token: Token): string {
  const target = aliasOf(token.value);
  if (target !== undefined) {
    const name = cssName(target);
    const fixed = FIXED.includes(target.split(".")[0] ?? "");
    if (token.lamina.followsAccent) return `var(--paper-${cssName(swapAccent(target, DEFAULT_ACCENT))})`;
    if (name !== undefined && (fixed || scope(target) === scope(token.path))) return `var(--paper-${name})`;
  }
  return literal(resolve(tokens, token.path));
}

/** The declarations of every token under `prefix`; a typography token becomes two. */
function declarations(tokens: Map<string, Token>, prefix: string): [string, string][] {
  const out: [string, string][] = [];
  for (const [path, token] of tokens) {
    if (!path.startsWith(prefix)) continue;
    const name = cssName(path);
    if (name === undefined) continue;
    if (token.type === "typography") out.push(...typography(tokens, name, token));
    else out.push([name, cssValue(tokens, token)]);
  }
  return out;
}

function typography(tokens: Map<string, Token>, name: string, token: Token): [string, string][] {
  const v = token.value as Typography;
  const family = cssName(aliasOf(v.fontFamily) ?? "");
  const size = literal(resolve(tokens, aliasOf(v.fontSize) ?? ""));
  if (family === undefined) throw new Error(`${token.path}: fontFamily must name a font token`);
  return [
    [name, `${v.fontWeight} ${size}/${v.lineHeight} var(--paper-${family})`],
    [`${name}-letter-spacing`, length(v.letterSpacing)],
  ];
}

// ---- CSS -----------------------------------------------------------------------------------

interface Block {
  comment: string;
  selectors: string[];
  decls: [string, string][];
  media?: string;
}

function blocks(tokens: Map<string, Token>): Block[] {
  const decl = (prefix: string) => declarations(tokens, prefix);
  const others = ACCENTS.filter((a) => a !== DEFAULT_ACCENT);
  const sys = ":root:not([data-theme])";
  const fixed = FIXED.flatMap((g) => decl(`${g}.`));
  const reduced = [...tokens.values()].flatMap((t): [string, string][] => {
    const r = t.lamina.reducedMotion;
    return r === undefined ? [] : [[cssName(t.path) ?? "", `${r.value}${r.unit}`]];
  });
  return [
    { comment: "Fixed: every theme and appearance", selectors: [":root"], decls: fixed },
    {
      comment: "Paper light (the default) with the default accent",
      selectors: [":root", '[data-theme="light"]'],
      decls: [...decl("theme.light."), ...decl(`accent.${DEFAULT_ACCENT}.light.`)],
    },
    ...ACCENTS.map((a) => ({
      comment: `Accent ${a}: light values and its page tints (page tints follow the accent in every theme)`,
      selectors: [...(a === DEFAULT_ACCENT ? [":root"] : []), `[data-accent="${a}"]`],
      decls: [...decl(`accent.${a}.light.`), ...decl(`accent.${a}.page.`)],
    })),
    {
      comment: "Paper dark with the default accent",
      selectors: ['[data-theme="dark"]'],
      decls: [...decl("theme.dark."), ...decl(`accent.${DEFAULT_ACCENT}.dark.`)],
    },
    ...others.map((a) => ({
      comment: `Accent ${a}: dark values`,
      selectors: [`[data-theme="dark"][data-accent="${a}"]`],
      decls: decl(`accent.${a}.dark.`),
    })),
    {
      comment: "Match system: Paper dark when the system is dark and no theme is set",
      media: "(prefers-color-scheme: dark)",
      selectors: [sys],
      decls: [...decl("theme.dark."), ...decl(`accent.${DEFAULT_ACCENT}.dark.`)],
    },
    ...others.map((a) => ({
      comment: `Match system, accent ${a}`,
      media: "(prefers-color-scheme: dark)",
      selectors: [`${sys}[data-accent="${a}"]`],
      decls: decl(`accent.${a}.dark.`),
    })),
    {
      comment: "High contrast: system colours; the accent is ignored",
      selectors: ['[data-theme="high-contrast"]'],
      decls: decl("theme.high-contrast."),
    },
    {
      comment: "Forced colours: high contrast whatever the theme",
      media: "(forced-colors: active)",
      selectors: [":root", "[data-theme]"],
      decls: decl("theme.high-contrast."),
    },
    ...APPEARANCES.map((p) => ({
      comment: `Page appearance ${p}`,
      selectors: [...(p === "original" ? [":root"] : []), `[data-page-appearance="${p}"]`],
      decls: decl(`appearance.${p}.`),
    })),
    { comment: "Reduced motion", media: "(prefers-reduced-motion: reduce)", selectors: [":root"], decls: reduced },
  ];
}

/** tokens.css: one block per theme, accent and appearance, every selector in `:where()`. */
export function emitCss(tokens: Map<string, Token>): string {
  const out = [
    `/* ${HEADER}. */`,
    "/* Every selector is wrapped in :where(), so blocks win by order alone and any rule of yours",
    "   overrides them. Set data-theme and data-accent on the same element. */",
  ];
  for (const b of blocks(tokens)) {
    const indent = b.media === undefined ? "" : "  ";
    const body = [
      `${indent}:where(${b.selectors.join(", ")}) {`,
      ...b.decls.map(([n, v]) => `${indent}  --paper-${n}: ${v};`),
      `${indent}}`,
    ];
    out.push("", `/* ${b.comment} */`, ...(b.media === undefined ? body : [`@media ${b.media} {`, ...body, "}"]));
  }
  return `${out.join("\n")}\n`;
}

// ---- TypeScript ----------------------------------------------------------------------------

/** A resolved token as a TypeScript value: px and ms as numbers, colours and stacks as CSS. */
function tsValue(token: Token): unknown {
  switch (token.type) {
    case "dimension": {
      const d = token.value as Dimension;
      if (d.unit !== "px") throw new Error(`${token.path}: only px dimensions have a TypeScript form`);
      return d.value;
    }
    case "duration":
      return (token.value as Dimension).value;
    case "number":
      return token.value;
    default:
      return literal(token);
  }
}

function tsTypography(tokens: Map<string, Token>, token: Token): unknown {
  const v = token.value as Typography;
  return {
    fontFamily: literal(resolve(tokens, aliasOf(v.fontFamily) ?? "")),
    fontSize: tsValue(resolve(tokens, aliasOf(v.fontSize) ?? "")),
    fontWeight: v.fontWeight,
    lineHeight: v.lineHeight,
    letterSpacing: v.letterSpacing.value,
  };
}

/** `{ name: value }` for the tokens under `prefix`, keyed by CSS name less `strip`. */
function record(tokens: Map<string, Token>, prefix: string, strip: string, accent = DEFAULT_ACCENT) {
  const out: Record<string, unknown> = {};
  for (const [path, token] of tokens) {
    if (!path.startsWith(prefix)) continue;
    const name = cssName(path) ?? "";
    const key = name.startsWith(strip) ? name.slice(strip.length) : name;
    out[key] = token.type === "typography" ? tsTypography(tokens, token) : tsValue(resolveFor(tokens, path, accent));
  }
  return out;
}

function themeRecord(tokens: Map<string, Token>, theme: string, accent: string) {
  if (theme === "high-contrast") return record(tokens, "theme.high-contrast.", "");
  return { ...record(tokens, `theme.${theme}.`, ""), ...record(tokens, `accent.${accent}.${theme}.`, "") };
}

const per = <T>(names: readonly string[], f: (n: string) => T) => Object.fromEntries(names.map((n) => [n, f(n)]));

function constant(doc: string, name: string, value: unknown): string {
  return `/** ${doc} */\nexport const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

/** tokens.ts: the same values as `as const` objects, and the unions that name them. */
export function emitTs(tokens: Map<string, Token>): string {
  const names = [...tokens.keys()].flatMap((p) => {
    const t = tokens.get(p);
    const n = cssName(p);
    return n === undefined || t === undefined ? [] : t.type === "typography" ? [n, `${n}-letter-spacing`] : [n];
  });
  const colours = [...tokens].filter(([p, t]) => p.startsWith("theme.high-contrast.") && t.type === "color");
  const union = (xs: string[]) => [...new Set(xs)].map((x) => JSON.stringify(x)).join(" | ");
  return [
    `// ${HEADER}.`,
    "",
    constant(
      "The UI themes, each with every accent: `THEMES.dark.blue.surface`.",
      "THEMES",
      per(THEMES, (t) => per(ACCENTS, (a) => themeRecord(tokens, t, a))),
    ),
    constant(
      "The page appearances, each with every accent (the selection tint and find outline follow it).",
      "PAGE_APPEARANCES",
      per(APPEARANCES, (p) => per(ACCENTS, (a) => record(tokens, `appearance.${p}.`, "page-", a))),
    ),
    constant(
      "Highlight and annotation colours: the same in every theme and appearance.",
      "ANNOTATION_COLOURS",
      record(tokens, "annotation.", "annotation-"),
    ),
    constant(
      "The fixed content palettes (line, page content, outline, signature, presence, diff).",
      "CONTENT_COLOURS",
      record(tokens, "content.", "content-"),
    ),
    constant("Font stacks, as CSS `font-family` values.", "FONTS", record(tokens, "font.", "font-")),
    constant(
      "The type scale: size in px, unitless line height, letter spacing in px.",
      "TYPE",
      record(tokens, "type.", "type-"),
    ),
    constant("The spacing scale, in px.", "SPACE", record(tokens, "semantic.space-", "space-")),
    constant("Corner radii, in px.", "RADIUS", record(tokens, "semantic.radius-", "radius-")),
    constant("Component sizes, in px.", "COMPONENT", record(tokens, "component.", "")),
    constant(
      "Layout breakpoints, in px (CSS can't read custom properties in a media query).",
      "BREAKPOINTS",
      record(tokens, "breakpoint.", "breakpoint-"),
    ),
    constant("Durations, in ms.", "MOTION", record(tokens, "motion.", "duration-")),
    `/** A semantic colour every theme defines. */\nexport type SemanticColour = ${union(colours.map(([p]) => cssName(p) ?? ""))};\n`,
    `/** Every custom property the CSS declares, without \`--paper-\`. */\nexport type TokenName = ${union(names)};\n`,
  ].join("\n");
}

// ---- contrast table ------------------------------------------------------------------------

function row(m: Measured[]): string {
  const first = m[0];
  if (first === undefined) return "";
  const ratios = m.map((x) => (x.ratio === undefined ? "browser" : x.ratio.toFixed(2)));
  const note = first.waived ?? "";
  return `| \`${first.fg}\` | \`${first.on}\` | ${first.kind} ≥ ${first.min} | ${ratios.join(" | ")} | ${note} |`;
}

/** CONTRAST.md: every declared pair and its ratio, per theme and appearance, one column per accent. */
export function emitContrast(tokens: Map<string, Token>): string {
  const all = contexts(tokens).map(({ ctx, accent }) => ({
    label: ctx.label,
    accent,
    pairs: measure(tokens, ctx, accent),
  }));
  const sections: string[] = [];
  const table = (title: string, columns: string[], groups: Measured[][]) => {
    sections.push(`## ${title}`, "", `| Foreground | On | Needs | ${columns.join(" | ")} | Waived |`);
    sections.push(`| --- | --- | --- | ${columns.map(() => "---").join(" | ")} | --- |`, ...groups.map(row), "");
  };
  const byAccent = (prefix: string) => {
    const sets = ACCENTS.map((a) => all.find((c) => c.accent === a && c.label === `${prefix} · ${a}`)?.pairs ?? []);
    return (sets[0] ?? []).map((_, i) => sets.map((s) => s[i]).filter((m): m is Measured => m !== undefined));
  };
  for (const t of ["light", "dark"]) table(`Paper ${t}`, [...ACCENTS], byAccent(t));
  table(
    "High contrast",
    ["Default"],
    (all.find((c) => c.label === "high-contrast")?.pairs ?? []).map((m) => [m]),
  );
  for (const p of APPEARANCES.filter((x) => x !== "high-contrast"))
    table(`Page: ${p}`, [...ACCENTS], byAccent(`page ${p}`));
  table(
    "Page: high-contrast",
    ["Default"],
    (all.find((c) => c.label === "page high-contrast")?.pairs ?? []).map((m) => [m]),
  );
  table(
    "Fixed colours",
    ["Ratio"],
    measure(tokens, fixedContext(tokens), DEFAULT_ACCENT).map((m) => [m]),
  );
  return [
    `<!-- ${HEADER}. -->`,
    "",
    "# Contrast of every declared pair",
    "",
    "WCAG 2.x contrast ratios, translucent colours composited over what they sit on. `browser` marks a pair of system colours, which the browser test measures in each engine. Waived pairs are reported, not failed.",
    "",
    ...sections,
  ].join("\n");
}
