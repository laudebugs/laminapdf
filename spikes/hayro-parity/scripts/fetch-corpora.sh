#!/usr/bin/env bash
# Fetch the pdf.js and PDFBox test PDFs at pinned commits into ./corpora (gitignored)
# and write corpora.manifest.toml (source, commit, licence, SHA-256 per file).
#
# Only PDFs stored in the repositories are used: pdf.js `*.link` files (remote PDFs,
# some gone) are listed in the manifest's `skipped_links` count but not fetched.
# Downloaded files are data: nothing from them is executed, and the checkouts are
# sparse (PDFs only, plus the repository LICENSE files).
set -euo pipefail
cd "$(dirname "$0")/.."

PDFJS_REPO=https://github.com/mozilla/pdf.js.git
PDFJS_COMMIT=87b369cd9d4cfe415b587b26a8d81f486db02874
PDFBOX_REPO=https://github.com/apache/pdfbox.git
PDFBOX_COMMIT=43e0c588a76c66a7e738b6632fe245d886ce0826

fetch() { # name repo commit pattern...
  local name=$1 repo=$2 commit=$3; shift 3
  local dir="corpora/$name"
  if [ ! -d "$dir/.git" ]; then
    mkdir -p "$dir"
    git -C "$dir" init -q
    git -C "$dir" remote add origin "$repo"
  fi
  git -C "$dir" config core.sparseCheckout true
  git -C "$dir" sparse-checkout set --no-cone "$@" /LICENSE.txt /LICENSE
  git -C "$dir" fetch -q --depth 1 --filter=blob:none origin "$commit"
  git -C "$dir" -c advice.detachedHead=false checkout -q FETCH_HEAD
  test "$(git -C "$dir" rev-parse HEAD)" = "$commit"
}

fetch pdfjs "$PDFJS_REPO" "$PDFJS_COMMIT" '/test/pdfs/*.pdf' '/test/pdfs/*.link'
fetch pdfbox "$PDFBOX_REPO" "$PDFBOX_COMMIT" '*.pdf'

hash_list() { # dir
  # Only files actually checked out (the index also lists sparse-excluded paths).
  (cd "$1" && find . -path ./.git -prune -o -type f -name '*.pdf' -print0 | xargs -0 shasum -a 256 \
    | sed 's#  \./#  #' | LC_ALL=C sort -k2)
}

{
  echo "# Generated by scripts/fetch-corpora.sh. Files live in corpora/ (gitignored, ADR 0018 §3)."
  echo "# Per-file licences: both repositories are Apache-2.0; individual test PDFs come from"
  echo "# bug reports and carry no separate licence statement, so none may be copied into fixtures/."
  for c in pdfjs pdfbox; do
    if [ $c = pdfjs ]; then repo=$PDFJS_REPO; commit=$PDFJS_COMMIT; else repo=$PDFBOX_REPO; commit=$PDFBOX_COMMIT; fi
    echo
    echo "[$c]"
    echo "source = \"$repo\""
    echo "commit = \"$commit\""
    echo "licence = \"Apache-2.0 (repository)\""
    echo "skipped_links = $(cd corpora/$c && find . -path ./.git -prune -o -type f -name '*.link' -print | wc -l | tr -d ' ')"
    echo "files = ["
    hash_list "corpora/$c" | while read -r sha path; do echo "  { path = \"$path\", sha256 = \"$sha\" },"; done
    echo "]"
  done
} > corpora.manifest.toml

grep -c sha256 corpora.manifest.toml
